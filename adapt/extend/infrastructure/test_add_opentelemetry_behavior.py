# BEHAVIOR-08: setup.py importable without opentelemetry SDK
# ---------------------------------------------------------------------------

def test_b08_setup_module_loads_without_sdk(project_dir: Path) -> None:
    """B-08: app/telemetry/setup.py imports without raising even without SDK."""
    setup_file = project_dir / "app" / "telemetry" / "setup.py"
    assert setup_file.exists(), "app/telemetry/setup.py not found"

    spec = importlib.util.spec_from_file_location(
        "app.telemetry.setup_behavior_test", str(setup_file)
    )
    assert spec is not None and spec.loader is not None

    orig = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    try:
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)  # type: ignore[attr-defined]
    except Exception as exc:
        raise AssertionError(
            f"app/telemetry/setup.py raised on import: {exc}"
        ) from exc
    finally:
        sys.path[:] = orig

    assert hasattr(module, "init_telemetry"), "init_telemetry not found in setup.py"
    assert hasattr(module, "get_tracer"), "get_tracer not found in setup.py"


