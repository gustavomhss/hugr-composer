# ---------------------------------------------------------------------------
# BEHAVIOR-07: ruff F401 clean on generated telemetry package
# ---------------------------------------------------------------------------

def test_b07_ruff_f401_clean(project_dir: Path) -> None:
    """B-07: No unused imports (F401) in app/telemetry/."""
    import shutil

    ruff_bin = shutil.which("ruff")
    if ruff_bin is None:
        pytest.skip("ruff not found in PATH — skipping F401 check")

    telemetry_dir = project_dir / "app" / "telemetry"
    if not telemetry_dir.exists():
        return

    for f in sorted(telemetry_dir.rglob("*.py")):
        result = subprocess.run(
            [ruff_bin, "check", "--select=F401", str(f)],
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, (
            f"ruff F401 violations in {f}:\n{result.stdout}{result.stderr}"
        )


