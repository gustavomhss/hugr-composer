def test_b05_cors_config_middleware_importable(project_dir: Path) -> None:
    """B-05: app/middleware/cors_config.py must be importable without raising."""
    cors_file = project_dir / "app" / "middleware" / "cors_config.py"
    assert cors_file.exists()
    spec = importlib.util.spec_from_file_location(
        "app.middleware.cors_config_b05", str(cors_file)
    )
    assert spec and spec.loader
    orig = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)  # type: ignore[attr-defined]
    except Exception as exc:
        raise AssertionError(f"cors_config.py raised on import: {exc}") from exc
    finally:
        sys.path[:] = orig
    assert hasattr(mod, "CORSConfigMiddleware")


