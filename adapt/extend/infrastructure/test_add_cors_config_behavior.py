# BEHAVIOR-06: all functions <= 50 LOC
# ---------------------------------------------------------------------------

def test_b06_all_generated_functions_under_50_loc(project_dir: Path) -> None:
    """B-06: All generated functions in cors_config.py are <= 50 LOC."""
    cors_file = project_dir / "app" / "middleware" / "cors_config.py"
    violations: list[str] = []
    if cors_file.exists():
        tree = ast.parse(cors_file.read_text())
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                loc = (node.end_lineno or node.lineno) - node.lineno + 1
                if loc > 50:
                    violations.append(f"cors_config.py:{node.name} ({loc} LOC)")
    assert not violations, "Functions > 50 LOC:\n" + "\n".join(violations)


