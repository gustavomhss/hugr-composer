def test_b06_client_module_importable(project_dir: Path) -> None:
    """B-06: app/workflows/client.py must be importable (SDK absent is fine)."""
    client_file = project_dir / "app" / "workflows" / "client.py"
    assert client_file.exists(), "app/workflows/client.py must exist"
    source = client_file.read_text()
    try:
        ast.parse(source)
    except SyntaxError as exc:
        pytest.fail(f"client.py has a SyntaxError: {exc}")
    # Import attempt: success or ModuleNotFoundError (SDK absent) — both valid
    project_str = str(project_dir)
    if project_str not in sys.path:
        sys.path.insert(0, project_str)
    sys.modules.pop("app.workflows.client", None)
    try:
        importlib.import_module("app.workflows.client")
    except (ModuleNotFoundError, ImportError):
        pass  # temporalio not installed — acceptable


def test_b07_config_fields_present(project_dir: Path) -> None:
    """B-07: TEMPORAL_* fields are present in app/core/config.py."""
    config_file = project_dir / "app" / "core" / "config.py"
    content = config_file.read_text()
    for field in ("TEMPORAL_HOST", "TEMPORAL_NAMESPACE", "TEMPORAL_TASK_QUEUE"):
        assert field in content, f"Config field {field} missing from config.py"


def test_b08_main_py_boots_without_temporalio(project_dir: Path) -> None:
    """B-08: app.main imports cleanly even when temporalio is not installed.

    INV-04: app.main MUST import cleanly without optional SDKs installed.
    """
    project_str = str(project_dir)
    if project_str not in sys.path:
        sys.path.insert(0, project_str)
    _clear_app_modules()
    try:
        main_module = importlib.import_module("app.main")
        assert hasattr(main_module, "app"), "app.main must expose an 'app' ASGI object"
    except ModuleNotFoundError as exc:
        if "temporalio" in str(exc):
            pytest.fail(
                "app.main raised ModuleNotFoundError for temporalio — "
                "SDK imports must be lazy (inside function bodies). "
                f"Original error: {exc}"
            )
        raise


