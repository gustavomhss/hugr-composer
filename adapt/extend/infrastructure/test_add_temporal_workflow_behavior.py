def _patch_project(project_dir: Path) -> None:
    """Apply SQLite + idempotency stubs to the fixture project."""
    (project_dir / "app" / "core" / "db.py").write_text(_SQLITE_DB_PY)
    (project_dir / "app" / "middleware" / "idempotency.py").write_text(
        _PASSTHROUGH_IDEMPOTENCY_PY
    )


def _clear_app_modules() -> None:
    """Remove cached ``app.*`` modules so fresh imports resolve correctly."""
    to_remove = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in to_remove:
        del sys.modules[key]


def _load_app(project_dir: Path) -> Any:
    """Load ``app.main:app`` from *project_dir*."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    _clear_app_modules()
    try:
        app_module = importlib.import_module("app.main")
    finally:
        sys.path[:] = _orig_path
    return app_module.app


def _setup_project() -> tuple[Path, Any]:
    """Create fixture project, apply tool, patch, load ASGI app."""
    project_dir = create_fixture_project(name="tw_behavior")
    result = add_temporal_workflow(ToolInput(project_dir=str(project_dir)))
    assert result.status == "success", (
        f"add_temporal_workflow failed: {result.error}\nnotes: {result.notes}"
    )
    _patch_project(project_dir)
    # Register the workflows router manually (main.py is not touched by design)
    project_str = str(project_dir)
    if project_str not in sys.path:
        sys.path.insert(0, project_str)
    _clear_app_modules()
    app_module = importlib.import_module("app.main")
    asgi_app = app_module.app
    wf_routes_mod = importlib.import_module("app.api.routes.workflows")
    asgi_app.include_router(wf_routes_mod.router)
    return project_dir, asgi_app


