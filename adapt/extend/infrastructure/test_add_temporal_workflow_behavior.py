# B-02: POST /workflows/start → not 404
# ---------------------------------------------------------------------------

@pytest.mark.anyio
async def test_b02_start_workflow_endpoint_exists(asgi_app: Any) -> None:
    """B-02: POST /workflows/start must exist (not 404).

    Without Temporal server the handler returns 503 (acceptable).
    404 means the route was not registered — that is a failure.
    """
    transport = httpx.ASGITransport(app=asgi_app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post(
            "/workflows/start",
            json={"order_id": "ord-001", "amount_cents": 5000},
        )
    assert response.status_code != 404, (
        f"POST /workflows/start returned 404 — route not registered! "
        f"body: {response.text}"
    )
    # 401 (auth), 422 (validation), 503 (no Temporal), 202 (started) all acceptable
    assert response.status_code in (202, 401, 422, 500, 503), (
        f"Unexpected status {response.status_code}; body: {response.text}"
    )


