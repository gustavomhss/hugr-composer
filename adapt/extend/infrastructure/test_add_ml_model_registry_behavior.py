_SQLITE_DB_PY = textwrap.dedent("""\
    \"\"\"Patched db.py — SQLite+aiosqlite, no Docker required.

    Uses a *file-based* SQLite DB (not in-memory) so the same tables
    survive across the multiple connections opened by FastAPI handlers.
    In-memory SQLite uses a per-connection database — the connection
    opened by ``init_db`` creates the tables, then the per-request
    connections open a fresh, empty database and cannot see them.
    \"\"\"

    import tempfile
    import os
    from sqlalchemy.ext.asyncio import create_async_engine

    # Use a stable temp file so all connections share the same database.
    _db_file = os.path.join(tempfile.gettempdir(), "ml_behavior_test.db")
    engine = create_async_engine(
        f"sqlite+aiosqlite:///{_db_file}",
        echo=False,
        future=True,
        connect_args={"check_same_thread": False},
    )


    async def init_db() -> None:
        \"\"\"Create all tables from SQLAlchemy metadata (file-based SQLite).\"\"\"
        from app.models.base import Base
        import app.models  # noqa: F401  — ensures all models are registered
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)


    __all__ = ["engine", "init_db"]
""")

_PASSTHROUGH_IDEMPOTENCY_PY = textwrap.dedent("""\
    \"\"\"Patched idempotency.py — pass-through stub (no Redis).\"\"\"

    from __future__ import annotations

    from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
    from starlette.requests import Request
    from starlette.responses import Response


    class IdempotencyMiddleware(BaseHTTPMiddleware):
        \"\"\"No-op pass-through stub for testing without Redis.\"\"\"

        async def dispatch(
            self,
            request: Request,
            call_next: RequestResponseEndpoint,
        ) -> Response:
            return await call_next(request)
""")


