# ---------------------------------------------------------------------------
# BEHAVIOR-05: No ML framework imports at top-level in any app/ file
# ---------------------------------------------------------------------------

def test_b05_no_ml_framework_top_level_imports(project_dir: Path) -> None:
    """B-05: No ML framework imported at module top level in any app/ file.

    This is a PURE DB registry — torch/sklearn/etc. must never appear at
    module scope.  App.main must boot without any ML package installed.
    """
    forbidden = {"torch", "sklearn", "tensorflow", "keras", "xgboost", "lightgbm"}
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue
        for child in ast.iter_child_nodes(tree):
            if isinstance(child, ast.Import):
                for alias in child.names:
                    top = alias.name.split(".")[0]
                    if top in forbidden:
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:"
                            f"{child.lineno}: import {alias.name}"
                        )
            elif isinstance(child, ast.ImportFrom) and child.module:
                top = child.module.split(".")[0]
                if top in forbidden:
                    violations.append(
                        f"{py_file.relative_to(project_dir)}:"
                        f"{child.lineno}: from {child.module} import ..."
                    )

    assert not violations, (
        "ML framework found at top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


# ---------------------------------------------------------------------------
# BEHAVIOR-06: All generated functions ≤ 50 LOC
# ---------------------------------------------------------------------------

def test_b06_all_functions_within_50_loc(project_dir: Path) -> None:
    """B-06: Every function in generated app/ must be ≤ 50 LOC (INV-05)."""
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if hasattr(node, "end_lineno") and node.end_lineno:
                    loc = node.end_lineno - node.lineno + 1
                    if loc > 50:
                        violations.append(
                            f"{py_file.relative_to(project_dir)}: "
                            f"def {node.name} ({loc} LOC > 50)"
                        )

    assert not violations, (
        "Functions exceeding 50 LOC found:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


