# ---------------------------------------------------------------------------
# BEHAVIOR-07: stripe NOT imported at module top level in any app/ file
# ---------------------------------------------------------------------------

def test_b07_stripe_not_top_level_import(project_dir: Path) -> None:
    """B-07: `import stripe` must NOT appear at module top level in any app/ file."""
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        source = py_file.read_text()
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue
        for node in tree.body:
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "stripe" or alias.name.startswith("stripe."):
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:{node.lineno}: import stripe"
                        )
            elif isinstance(node, ast.ImportFrom):
                if node.module and (
                    node.module == "stripe" or node.module.startswith("stripe.")
                ):
                    violations.append(
                        f"{py_file.relative_to(project_dir)}:{node.lineno}: from stripe import ..."
                    )

    assert not violations, (
        "stripe found at top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


