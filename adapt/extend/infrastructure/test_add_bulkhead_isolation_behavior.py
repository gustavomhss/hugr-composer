# ---------------------------------------------------------------------------
# B-07: Lazy SDK imports verified via AST
# ---------------------------------------------------------------------------

def test_b07_lazy_sdk_imports(project_dir: Path) -> None:
    """B-07: No optional SDKs are imported at module top-level in OUR generated files."""
    # Only scan the directories we generated — not pre-existing project files
    generated_dirs = [
        project_dir / "app" / "resilience",
        project_dir / "app" / "middleware",
    ]
    optional_sdks = {"redis", "stripe", "boto3", "psutil", "prometheus_client"}
    violations: list[str] = []
    for check_dir in generated_dirs:
        if not check_dir.exists():
            continue
        for py_file in check_dir.rglob("*.py"):
            source = py_file.read_text()
            try:
                tree = ast.parse(source)
            except SyntaxError:
                continue
            for node in tree.body:
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        root_name = alias.name.split(".")[0]
                        if root_name in optional_sdks:
                            violations.append(f"{py_file.name}:{node.lineno} import {alias.name}")
                elif isinstance(node, ast.ImportFrom):
                    if node.module:
                        root_name = node.module.split(".")[0]
                        if root_name in optional_sdks:
                            violations.append(
                                f"{py_file.name}:{node.lineno} from {node.module} import ..."
                            )
    assert not violations, (
        "Optional SDKs found at top-level in generated files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


# ---------------------------------------------------------------------------
# B-08: All generated functions <= 50 LOC
# ---------------------------------------------------------------------------

def test_b08_all_functions_max_50_loc(project_dir: Path) -> None:
    """B-08: No function in generated resilience or middleware files exceeds 50 LOC."""
    resilience_dir = project_dir / "app" / "resilience"
    middleware_dir = project_dir / "app" / "middleware"
    violations: list[str] = []
    check_dirs = []
    if resilience_dir.exists():
        check_dirs.append(resilience_dir)
    if middleware_dir.exists():
        check_dirs.append(middleware_dir)
    for d in check_dirs:
        for py_file in d.rglob("*.py"):
            tree = ast.parse(py_file.read_text())
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    loc = (node.end_lineno or node.lineno) - node.lineno + 1
                    if loc > 50:
                        violations.append(
                            f"{py_file.name}:{node.lineno} {node.name}() = {loc} LOC"
                        )
    assert not violations, "Functions > 50 LOC:\n" + "\n".join(violations)


