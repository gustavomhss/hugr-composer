@pytest.mark.anyio
async def test_b02_bulkhead_rejects_when_full(project_dir: Path) -> None:
    """B-02: Bulkhead raises BulkheadFullError when max_concurrent is reached."""
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.resilience.bulkhead import Bulkhead, BulkheadFullError
        from app.resilience.pool_config import BulkheadConfig
        bulkhead = Bulkhead(BulkheadConfig(limits={"test_group": 1}))
        pool = bulkhead.acquire("test_group")

        async def _exhaust_and_try() -> None:
            # Exhaust the semaphore
            await pool.__aenter__()
            try:
                # Now this should fail — pool is full
                with pytest.raises(BulkheadFullError):
                    await pool.__aenter__()
            finally:
                await pool.__aexit__(None, None, None)

        await _exhaust_and_try()
    finally:
        sys.path.remove(str(project_dir))


