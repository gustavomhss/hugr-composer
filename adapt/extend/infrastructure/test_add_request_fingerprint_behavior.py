# BEHAVIOR-02: hasher.py importable and produces deterministic fingerprints
# ---------------------------------------------------------------------------

def test_b02_hasher_importable_and_deterministic(project_dir: Path) -> None:
    """B-02: app/fingerprint/hasher.py importable; same input → same fingerprint."""
    hasher_file = project_dir / "app" / "fingerprint" / "hasher.py"
    assert hasher_file.exists(), "hasher.py not found"
    spec = importlib.util.spec_from_file_location(
        "app.fingerprint.hasher_behavior_test", str(hasher_file)
    )
    assert spec is not None and spec.loader is not None
    _orig = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    try:
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)  # type: ignore[attr-defined]
    except Exception as exc:
        raise AssertionError(f"hasher.py raised on import: {exc}") from exc
    finally:
        sys.path[:] = _orig

    assert hasattr(module, "RequestFingerprinter"), "RequestFingerprinter not found"
    fingerprinter = module.RequestFingerprinter()
    fp1 = fingerprinter.compute("user1", "POST", "/api/items", b'{"a":1,"b":2}')
    fp2 = fingerprinter.compute("user1", "POST", "/api/items", b'{"b":2,"a":1}')
    assert fp1 == fp2, "Fingerprints must be identical for body with same keys in different order"
    assert len(fp1) == 64, "SHA-256 fingerprint must be 64 chars"


