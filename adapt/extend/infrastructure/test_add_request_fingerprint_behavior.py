# ---------------------------------------------------------------------------
# BEHAVIOR-05: redis NOT at top level in store.py
# ---------------------------------------------------------------------------

def test_b05_redis_not_top_level_in_store(project_dir: Path) -> None:
    """B-05: redis must NOT appear in top-level imports in store.py."""
    store_file = project_dir / "app" / "fingerprint" / "store.py"
    source = store_file.read_text()
    tree = ast.parse(source)
    violations: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                if "redis" in alias.name.lower():
                    violations.append(f"line {node.lineno}: import {alias.name}")
        elif isinstance(node, ast.ImportFrom) and node.module:
            if "redis" in node.module.lower():
                violations.append(f"line {node.lineno}: from {node.module} import ...")
    assert not violations, (
        "redis found at top level in store.py:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


# ---------------------------------------------------------------------------
# BEHAVIOR-06: all generated functions <= 50 LOC
# ---------------------------------------------------------------------------

def test_b06_no_function_over_50_loc(project_dir: Path) -> None:
    """B-06: All functions in app/fingerprint/ and app/middleware/fingerprint.py <= 50 LOC."""
    check_dirs = [
        project_dir / "app" / "fingerprint",
        project_dir / "app" / "middleware",
    ]
    violations: list[str] = []
    for check_dir in check_dirs:
        if not check_dir.exists():
            continue
        for py_file in sorted(check_dir.glob("*.py")):
            if "fingerprint" not in py_file.name and check_dir.name == "middleware":
                continue
            try:
                tree = ast.parse(py_file.read_text())
            except SyntaxError:
                continue
            for node in ast.walk(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    if node.end_lineno:
                        loc = node.end_lineno - node.lineno + 1
                        if loc > 50:
                            violations.append(
                                f"{py_file.name}::{node.name} ({loc} LOC)"
                            )
    assert not violations, (
        "Functions exceed 50 LOC in fingerprint/middleware:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


