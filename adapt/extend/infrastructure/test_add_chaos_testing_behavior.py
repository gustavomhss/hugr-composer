def test_b04_production_guard_blocks_enable_in_prod(project_dir: Path) -> None:
    """B-04: ChaosEngine.enable() must be blocked when ENVIRONMENT=production."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
