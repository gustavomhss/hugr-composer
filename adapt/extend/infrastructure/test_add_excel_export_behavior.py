# BEHAVIOR-03: POST /api/v1/exports/excel returns xlsx content-type
# ---------------------------------------------------------------------------

@pytest.mark.anyio
async def test_b03_excel_export_returns_xlsx(asgi_app: Any) -> None:
    """B-03: POST /api/v1/exports/excel returns Excel MIME type when openpyxl available."""
    try:
        import openpyxl  # noqa: F401
    except ImportError:
        pytest.skip("openpyxl not installed — cannot test Excel generation")

    transport = httpx.ASGITransport(app=asgi_app)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        response = await client.post(
            "/api/v1/exports/excel",
            json={"model_name": "Item", "filters": {}},
        )

    if response.status_code == 200:
        ct = response.headers.get("content-type", "")
        assert "spreadsheetml" in ct or "octet-stream" in ct, (
            f"Expected Excel MIME type, got: {ct}"
        )
    else:
        assert response.status_code in (400, 401, 422, 500), (
            f"Unexpected status {response.status_code}"
        )


