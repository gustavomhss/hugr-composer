# BEHAVIOR-08: ExcelExporter boots without openpyxl installed
# ---------------------------------------------------------------------------

def test_b08_exporter_module_loads_without_openpyxl(project_dir: Path) -> None:
    """B-08: app/exports/excel.py imports without raising even without openpyxl."""
    import importlib.util

    excel_file = project_dir / "app" / "exports" / "excel.py"
    assert excel_file.exists(), "app/exports/excel.py not found"

    spec = importlib.util.spec_from_file_location(
        "app.exports.excel_behavior_test", str(excel_file)
    )
    assert spec is not None and spec.loader is not None

    orig = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    try:
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)  # type: ignore[attr-defined]
    except Exception as exc:
        raise AssertionError(
            f"app/exports/excel.py raised on import: {exc}"
        ) from exc
    finally:
        sys.path[:] = orig

    assert hasattr(module, "ExcelExporter"), "ExcelExporter class not found after import"


