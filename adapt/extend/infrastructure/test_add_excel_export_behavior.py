# BEHAVIOR-04: openpyxl import is lazy (AST verified)
# ---------------------------------------------------------------------------

def test_b04_openpyxl_import_is_lazy(project_dir: Path) -> None:
    """B-04: app/exports/excel.py must not import openpyxl at module level."""
    excel_file = project_dir / "app" / "exports" / "excel.py"
    assert excel_file.exists(), "app/exports/excel.py not found"
    tree = ast.parse(excel_file.read_text())
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                assert "openpyxl" not in alias.name.lower(), (
                    f"openpyxl imported at module level in excel.py: {alias.name}"
                )
        elif isinstance(node, ast.ImportFrom) and node.module:
            assert "openpyxl" not in node.module.lower(), (
                f"openpyxl imported at module level in excel.py: {node.module}"
            )


# ---------------------------------------------------------------------------
# BEHAVIOR-05: all generated functions ≤50 LOC
# ---------------------------------------------------------------------------

def test_b05_all_functions_50_loc(project_dir: Path) -> None:
    """B-05: Every function in app/exports/ must be ≤50 LOC."""
    exports_dir = project_dir / "app" / "exports"
    assert exports_dir.exists(), "app/exports/ not found"
    for py_file in sorted(exports_dir.rglob("*.py")):
        tree = ast.parse(py_file.read_text())
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if hasattr(node, "end_lineno") and node.end_lineno:
                    loc = node.end_lineno - node.lineno + 1
                    assert loc <= 50, (
                        f"Function '{node.name}' in {py_file} has {loc} LOC (limit: 50)"
                    )


