def test_b06_config_fields_4_space_indent(project_dir: Path) -> None:
    """B-06: EXCEL_* config fields must be 4-space indented (inside class)."""
    config_file = project_dir / "app" / "core" / "config.py"
    assert config_file.exists(), "app/core/config.py not found"
    content = config_file.read_text()
    for field in ("EXCEL_MAX_ROWS", "EXCEL_CHUNK_SIZE"):
        assert field in content, f"{field} not in config.py"
    for line in content.splitlines():
        if "EXCEL_MAX_ROWS" in line and ":" in line:
            assert line.startswith("    "), (
                f"EXCEL_MAX_ROWS not 4-space indented: {line!r}"
            )
            break


# ---------------------------------------------------------------------------
# BEHAVIOR-07: ruff F401 clean on generated exports package
# ---------------------------------------------------------------------------

def test_b07_ruff_f401_clean(project_dir: Path) -> None:
    """B-07: No unused imports (F401) in app/exports/."""
    import shutil

    ruff_bin = shutil.which("ruff")
    if ruff_bin is None:
        pytest.skip("ruff not found in PATH — skipping F401 check")

    exports_dir = project_dir / "app" / "exports"
    if not exports_dir.exists():
        return

    for f in sorted(exports_dir.rglob("*.py")):
        result = subprocess.run(
            [ruff_bin, "check", "--select=F401", str(f)],
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, (
            f"ruff F401 violations in {f}:\n{result.stdout}{result.stderr}"
        )


