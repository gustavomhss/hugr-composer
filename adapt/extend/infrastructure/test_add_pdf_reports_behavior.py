# BEHAVIOR-07: ruff F401 clean on generated reports package
# ---------------------------------------------------------------------------

def test_b07_ruff_f401_clean(project_dir: Path) -> None:
    """B-07: No unused imports (F401) in app/reports/ and app/api/routes/reports.py."""
    import shutil

    ruff_bin = shutil.which("ruff")
    if ruff_bin is None:
        pytest.skip("ruff not found in PATH — skipping F401 check")

    files_to_check: list[Path] = []
    reports_dir = project_dir / "app" / "reports"
    if reports_dir.exists():
        files_to_check.extend(reports_dir.rglob("*.py"))
    route_file = project_dir / "app" / "api" / "routes" / "reports.py"
    if route_file.exists():
        files_to_check.append(route_file)
    schema_file = project_dir / "app" / "schemas" / "report.py"
    if schema_file.exists():
        files_to_check.append(schema_file)

    for f in files_to_check:
        result = subprocess.run(
            [ruff_bin, "check", "--select=F401", str(f)],
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, (
            f"ruff F401 violations in {f}:\n{result.stdout}{result.stderr}"
        )


