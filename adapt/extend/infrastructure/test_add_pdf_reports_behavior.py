# BEHAVIOR-04: weasyprint import is lazy (AST verified)
# ---------------------------------------------------------------------------

def test_b04_weasyprint_import_is_lazy(project_dir: Path) -> None:
    """B-04: app/reports/engine.py must not import weasyprint at module level."""
    engine_file = project_dir / "app" / "reports" / "engine.py"
    assert engine_file.exists(), "app/reports/engine.py not found"
    tree = ast.parse(engine_file.read_text())
    for node in tree.body:
        if isinstance(node, ast.Import):
            for alias in node.names:
                assert "weasyprint" not in alias.name.lower(), (
                    f"weasyprint imported at module level in engine.py: {alias.name}"
                )
        elif isinstance(node, ast.ImportFrom) and node.module:
            assert "weasyprint" not in node.module.lower(), (
                f"weasyprint imported at module level in engine.py: {node.module}"
            )


