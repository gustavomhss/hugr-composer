def _patch_project(project_dir: Path) -> None:
    """Apply SQLite + idempotency stubs to the fixture project."""
    (project_dir / "app" / "core" / "db.py").write_text(_SQLITE_DB_PY)
    (project_dir / "app" / "middleware" / "idempotency.py").write_text(
        _PASSTHROUGH_IDEMPOTENCY_PY
    )


def _load_app(project_dir: Path) -> Any:
    """Load ``app.main:app`` from *project_dir* in an isolated sys.path context.

    Each call evicts stale ``app.*`` modules so that tests that share the
    module-level singleton always get the version from *project_dir*.
    """
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))

    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]

    try:
        app_module = importlib.import_module("app.main")
    finally:
        sys.path[:] = _orig_path

    return app_module.app


def _setup_project() -> tuple[Path, Any]:
    """Create, apply tool, patch, and load the ASGI app.

    Returns:
        Tuple of (project_dir, asgi_app).
    """
    project_dir = create_fixture_project(name="s3_behavior")

    result = add_s3_storage(ToolInput(project_dir=str(project_dir)))
    assert result.status == "success", (
        f"add_s3_storage failed: {result.error}\nnotes: {result.notes}"
    )

    _patch_project(project_dir)

    asgi_app = _load_app(project_dir)
    return project_dir, asgi_app


