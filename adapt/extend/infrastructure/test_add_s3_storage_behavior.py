# BEHAVIOR-07: app/storage/config.py has StorageConfig and parses cleanly
# ---------------------------------------------------------------------------

def test_b07_storage_config_parses_and_has_class(project_dir: Path) -> None:
    """B-07: app/storage/config.py must parse cleanly and define StorageConfig.

    app/storage/config.py imports ``from app.core.config import settings`` which
    in turn pulls in the full Pydantic settings chain (asyncpg, PostgresDsn, etc.).
    Rather than trying to exec_module in isolation (which fails due to the
    transitive dependency chain), we verify the file:
    1. Contains valid Python (ast.parse succeeds).
    2. Defines a ``StorageConfig`` class at module scope.
    3. Defines a ``from_settings`` classmethod inside ``StorageConfig``.

    The full runtime import is validated implicitly by the ASGI boot tests
    (B-01 through B-05) — those load ``app.main`` which imports ``app.storage``
    which imports ``app.storage.config``.
    """
    config_file = project_dir / "app" / "storage" / "config.py"
    assert config_file.exists(), "app/storage/config.py not found"

    source = config_file.read_text()

    # 1. Valid Python
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        raise AssertionError(
            f"app/storage/config.py has a syntax error: {exc}"
        ) from exc

    # 2. StorageConfig class is defined at module scope
    class_names = [
        node.name
        for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef)
    ]
    assert "StorageConfig" in class_names, (
        f"StorageConfig class not found in app/storage/config.py; "
        f"found classes: {class_names}"
    )

    # 3. from_settings classmethod present in source
    assert "from_settings" in source, (
        "from_settings classmethod not found in app/storage/config.py"
    )


