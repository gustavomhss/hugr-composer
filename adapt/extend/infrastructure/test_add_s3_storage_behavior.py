def test_b06_storage_client_imports_without_crash(project_dir: Path) -> None:
    """B-06: app/storage/client.py must be importable without raising.

    The lazy boto3 import means the module loads cleanly even without boto3.
    """
    client_file = project_dir / "app" / "storage" / "client.py"
    assert client_file.exists(), "app/storage/client.py not found"

    spec = importlib.util.spec_from_file_location(
        "app.storage.client_behavior_test", str(client_file)
    )
    assert spec is not None and spec.loader is not None

    _orig = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    try:
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)  # type: ignore[attr-defined]
    except Exception as exc:
        raise AssertionError(
            f"app/storage/client.py raised on import: {exc}"
        ) from exc
    finally:
        sys.path[:] = _orig

    assert hasattr(module, "S3Client"), "S3Client class not found after import"
    assert hasattr(module, "get_s3_client"), "get_s3_client function not found after import"


