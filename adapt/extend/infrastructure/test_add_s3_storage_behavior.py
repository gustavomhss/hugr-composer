# ---------------------------------------------------------------------------
# BEHAVIOR-10: boto3 NOT imported at top-level in any app/ file except
#              internal function bodies inside app/storage/client.py
# ---------------------------------------------------------------------------

def test_b10_boto3_not_imported_at_top_level(project_dir: Path) -> None:
    """B-10: boto3 must NOT be a top-level import in any app/ .py file.

    boto3 is imported lazily inside ``S3Client.__init__`` so the application
    can boot without boto3 installed.  A top-level ``import boto3`` would
    break ``app.main`` import on machines lacking boto3.
    """
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        source = py_file.read_text()
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue  # Syntax errors caught by other tests

        # Only check module-level statements (direct children of the Module node)
        for child in ast.iter_child_nodes(tree):
            if isinstance(child, ast.Import):
                for alias in child.names:
                    if alias.name == "boto3" or alias.name.startswith("boto3."):
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:"
                            f"{child.lineno}: import boto3"
                        )
            elif isinstance(child, ast.ImportFrom):
                if child.module and (
                    child.module == "boto3"
                    or child.module.startswith("boto3.")
                ):
                    violations.append(
                        f"{py_file.relative_to(project_dir)}:"
                        f"{child.lineno}: from boto3 import ..."
                    )

    assert not violations, (
        "boto3 found at top-level (module scope) in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
        + "\nboto3 must be imported LAZILY inside S3Client.__init__ only."
    )


