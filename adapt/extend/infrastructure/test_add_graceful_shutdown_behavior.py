# ---------------------------------------------------------------------------
# B-08: verify no dead imports via AST walk on lifecycle files
# ---------------------------------------------------------------------------

def test_b08_no_dead_imports_in_lifecycle_files(project_dir: Path) -> None:
    """B-08: All imports in lifecycle files appear used in the module body."""
    lifecycle_dir = project_dir / "app" / "lifecycle"
    for py_file in sorted(lifecycle_dir.rglob("*.py")):
        source = py_file.read_text()
        tree = ast.parse(source)
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.names:
                # Skip __future__ imports — 'annotations' is a special directive
                if node.module == "__future__":
                    continue
                for alias in node.names:
                    name = alias.asname or alias.name
                    if name == "*" or name.startswith("_"):
                        continue
                    lines_using = [
                        ln for ln in source.splitlines()
                        if name in ln and "import" not in ln
                    ]
                    assert len(lines_using) >= 1, (
                        f"{py_file.name}: imported {name!r} appears unused"
                    )


