# B-10: ruff F401 — no dead imports in generated resilience files
# ---------------------------------------------------------------------------

def test_b10_no_dead_imports(project_dir: Path) -> None:
    """B-10: Generated resilience files have no obviously dead imports."""
    resilience_dir = project_dir / "app" / "resilience"
    middleware_dir = project_dir / "app" / "middleware"
    # Verify that key imports in each file are actually used
    shedder_file = resilience_dir / "load_shedder.py"
    if shedder_file.exists():
        content = shedder_file.read_text()
        tree = ast.parse(content)
        imported_names: set[str] = set()
        for node in tree.body:
            if isinstance(node, ast.Import):
                for alias in node.names:
                    imported_names.add(alias.asname or alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    imported_names.add(alias.asname or alias.name)
        # Check that each imported name actually appears in the file body
        for name in imported_names:
            assert name in content, (
                f"Imported '{name}' appears unused in {shedder_file.name}"
            )


