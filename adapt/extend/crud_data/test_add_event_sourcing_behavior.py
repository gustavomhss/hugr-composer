# B-03: Optimistic-concurrency append order (F-10 preservation)
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_b03_append_order_under_expected_version(asgi_app: Any) -> None:
    """B-03: F-10 preservation — appends with expected_version advance the stream sequentially.

    First append at expected_version=0 succeeds; second append at expected_version=0
    again (stale) should fail with 409 Conflict (optimistic concurrency).
    """
    transport = httpx.ASGITransport(app=asgi_app, raise_app_exceptions=False)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        first = await client.post(
            "/events/aggregate-f10?expected_version=0",
            json=[{"type": "Created", "payload": {"v": 1}}],
        )
        assert first.status_code in (200, 201), (
            f"first append should succeed; got {first.status_code}: {first.text}"
        )
        stale = await client.post(
            "/events/aggregate-f10?expected_version=0",
            json=[{"type": "Updated", "payload": {"v": 2}}],
        )
        assert stale.status_code == 409, (
            f"stale expected_version must return 409; got {stale.status_code}: {stale.text}"
        )


# ---------------------------------------------------------------------------
# B-04: Append-and-load round-trip preserves order
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_b04_append_then_load_preserves_order(asgi_app: Any) -> None:
    """B-04: Loaded events come back in append order."""
    transport = httpx.ASGITransport(app=asgi_app, raise_app_exceptions=False)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        for v, ev_type in enumerate(["E1", "E2", "E3"]):
            r = await client.post(
                f"/events/order-test?expected_version={v}",
                json=[{"type": ev_type, "payload": {"i": v}}],
            )
            assert r.status_code in (200, 201), f"append {v} failed: {r.status_code}: {r.text}"
        loaded = await client.get("/events/order-test")
        assert loaded.status_code == 200, f"load failed: {loaded.status_code}: {loaded.text}"
        body = loaded.json()
        events = body if isinstance(body, list) else body.get("events", body.get("data", []))
        types = [e.get("type") if isinstance(e, dict) else e for e in events]
        assert types[:3] == ["E1", "E2", "E3"], f"order lost: {types}"
