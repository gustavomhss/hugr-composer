# B-05: F-04 per-model opt-out — model WITHOUT is_deleted hard-deletes
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_b05_per_model_opt_out_hard_deletes(project_dir: Path) -> None:
    """B-05: F-04 — the patched delete() falls through to SQL DELETE for opt-out models.

    Constructs a model WITHOUT ``is_deleted`` in-memory and exercises
    CRUDBase.delete on it; the patched code must call session.delete (hard
    delete) because hasattr(obj, 'is_deleted') is False.
    """
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.crud.base import CRUDBase  # noqa: F401  (load the patched class)
        from sqlalchemy import Column, Integer, String
        from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine
        from sqlalchemy.orm import DeclarativeBase

        class _Base(DeclarativeBase):
            pass

        class OptOutModel(_Base):
            __tablename__ = "optout_model"
            id = Column(Integer, primary_key=True)
            name = Column(String, nullable=False)

        engine = create_async_engine("sqlite+aiosqlite:///:memory:")
        async with engine.begin() as conn:
            await conn.run_sync(_Base.metadata.create_all)
        session_factory = async_sessionmaker(engine, expire_on_commit=False)

        crud = CRUDBase(OptOutModel)
        async with session_factory() as session:
            obj = OptOutModel(id=1, name="ephemeral")
            session.add(obj)
            await session.flush()
            deleted = await crud.delete(session, 1)
            await session.commit()
            assert deleted is not None, "delete() must return the deleted object"
            # Hard-delete: a subsequent get() must return None because the row is gone.
            re_fetched = await crud.get(session, 1)
            assert re_fetched is None, (
                "Opt-out model must hard-delete; got a row back (F-04 regression)"
            )
        await engine.dispose()
    finally:
        sys.path[:] = _orig_path


# ---------------------------------------------------------------------------
# B-06: SPEC-v2 opt-in — a SoftDeleteMixin model soft-deletes (flag flip, no
# SQL DELETE) AND the global filter excludes it from reads, with include_deleted
# as the opt-out.
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_b06_opt_in_soft_deletes(project_dir: Path) -> None:
    """B-06: SPEC-v2 opt-in — a model that inherits SoftDeleteMixin is soft-deleted
    (is_deleted flipped True, no SQL DELETE) and is filtered out of reads by the
    GLOBAL do_orm_execute listener; ``include_deleted=True`` is the read opt-out.

    Re-anchored from the OLD design, where opt-in was an ad-hoc ``is_deleted``
    column on a standalone model and read exclusion came from a per-query
    ``CRUDBase.get`` rebind. SPEC-v2 (#19) makes opt-in mean *inheriting the
    emitted SoftDeleteMixin*: the global filter (app/core/soft_delete_filter.py)
    keys off that mixin via ``with_loader_criteria``, so reads exclude
    soft-deleted rows transparently while ``execution_options(include_deleted=
    True)`` opts back in. We exercise the REAL shipped artefacts: the emitted
    mixin (so the row is genuinely filterable) + the emitted filter module (so
    the listener is registered).
    """
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.crud.base import CRUDBase
        from app.models.mixins import SoftDeleteMixin
        from sqlalchemy import Column, Integer, String, Uuid, select
        from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine
        from sqlalchemy.orm import DeclarativeBase

        from app.core import soft_delete_filter  # noqa: F401  (registers the listener)

        class _Base(DeclarativeBase):
            pass

        # SoftDeleteMixin.deleted_by is an FK to ``users.id`` — provide a minimal
        # users table in the same metadata so the FK resolves at create_all.
        class _Users(_Base):
            __tablename__ = "users"
            id = Column(Uuid, primary_key=True)

        # Opt-in == inheriting the emitted SoftDeleteMixin (gains the 3 columns
        # AND is keyed by the global filter).
        class SoftModel(SoftDeleteMixin, _Base):
            __tablename__ = "soft_model"
            id = Column(Integer, primary_key=True)
            name = Column(String, nullable=False)

        engine = create_async_engine("sqlite+aiosqlite:///:memory:")
        async with engine.begin() as conn:
            await conn.run_sync(_Base.metadata.create_all)
        session_factory = async_sessionmaker(engine, expire_on_commit=False)

        crud = CRUDBase(SoftModel)
        async with session_factory() as session:
            obj = SoftModel(id=1, name="alive")
            session.add(obj)
            await session.flush()
            await crud.delete(session, 1)
            await session.commit()

        async with session_factory() as session:
            # Default reads go through the global do_orm_execute filter and must
            # exclude the soft-deleted row.
            filtered = await crud.get(session, 1)
            assert filtered is None, (
                "Global do_orm_execute filter must exclude soft-deleted rows from "
                "default reads (INV-SD-01 regression)."
            )
            # Opt-out: include_deleted=True returns the soft-deleted row.
            opted_in = await session.execute(
                select(SoftModel).where(SoftModel.id == 1).execution_options(include_deleted=True)
            )
            row = opted_in.scalar_one_or_none()
            assert row is not None, (
                "Soft-delete must NOT issue SQL DELETE; include_deleted=True must "
                "return the row (P1-#14 / opt-out regression)."
            )
            assert row.is_deleted is True, "is_deleted flag must be flipped True"
            assert row.deleted_at is not None, "deleted_at must be stamped"
        await engine.dispose()
    finally:
        sys.path[:] = _orig_path
