# ---------------------------------------------------------------------------
# B-04: SPEC-v2 — the domain model gains deletion columns via SoftDeleteMixin
# inheritance; the columns themselves live on the emitted mixin.
# ---------------------------------------------------------------------------


def test_b04_is_deleted_column_injected(project_dir: Path) -> None:
    """B-04: SPEC-v2 — the model inherits SoftDeleteMixin; the mixin declares the 3 columns.

    Re-anchored from the OLD design (an ``is_deleted``/``deleted_at`` column
    literal + Boolean/DateTime imports injected directly into every model file).
    SPEC-v2 (#19) instead emits ``app/models/mixins.py::SoftDeleteMixin`` carrying
    the deletion columns and rewrites each domain model's bases to inherit it, so
    the global do_orm_execute listener can key off that single class. We assert
    the real shipped behaviour: the model imports + actually inherits the mixin
    (AST), and the mixin declares all three deletion columns.
    """
    model_file = project_dir / "app" / "models" / "item.py"
    assert model_file.exists(), "item.py model missing"
    body = model_file.read_text()

    # The model imports + inherits the mixin (soft-delete is inert otherwise).
    assert "from app.models.mixins import SoftDeleteMixin" in body, (
        "Model must import SoftDeleteMixin (BUG C regression — soft-delete inert)."
    )
    import ast as _ast

    tree = _ast.parse(body)
    item_cls = next(
        (n for n in _ast.walk(tree) if isinstance(n, _ast.ClassDef) and n.name == "Item"),
        None,
    )
    assert item_cls is not None, "Item class not found in model file"
    base_names = {b.id for b in item_cls.bases if isinstance(b, _ast.Name)}
    assert "SoftDeleteMixin" in base_names, (
        "Item must inherit SoftDeleteMixin so it gains the deletion columns."
    )

    # The deletion columns live on the emitted mixin (single source of truth).
    mixin_file = project_dir / "app" / "models" / "mixins.py"
    assert mixin_file.exists(), "app/models/mixins.py not emitted — columns have no home."
    mixin_src = mixin_file.read_text()
    assert "class SoftDeleteMixin" in mixin_src, "SoftDeleteMixin class not emitted."
    for col in ("is_deleted", "deleted_at", "deleted_by"):
        assert col in mixin_src, f"{col} column NOT defined on SoftDeleteMixin."
    assert "Boolean" in mixin_src and "DateTime" in mixin_src, (
        "Boolean/DateTime must be imported by the mixin (it declares those columns)."
    )


