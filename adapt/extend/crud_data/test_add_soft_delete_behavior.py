# B-02: SPEC-v2 — delete() is rebound to the soft-delete-aware variant; reads
# are filtered GLOBALLY (do_orm_execute), so get/get_multi are NOT rebound.
# ---------------------------------------------------------------------------


def test_b02_crudbase_methods_rebound(project_dir: Path) -> None:
    """B-02: SPEC-v2 — only CRUDBase.delete is rebound to ``_sd_delete``.

    Re-anchored from the OLD design (which reassigned CRUDBase.get / get_multi /
    delete to per-query ``_sd_*`` filtering callables). SPEC-v2 (#19) moves read
    exclusion to a single GLOBAL ``do_orm_execute`` listener
    (app/core/soft_delete_filter.py) keyed off SoftDeleteMixin, so the read
    methods are deliberately left untouched — rebinding them would shadow the
    global filter. We assert the real shipped mechanism at runtime:

      * the emitted ``soft_delete_filter`` module registers a ``do_orm_execute``
        listener (the global read filter exists);
      * ``CRUDBase.delete`` is the ``_sd_delete`` soft-flip override;
      * ``CRUDBase.get`` / ``get_multi`` are NOT rebound to any ``_sd_*`` variant.
    """
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.crud import base as crud_base_mod

        # delete() is the soft-delete-aware override (INV-SD-03).
        assert crud_base_mod.CRUDBase.delete.__name__ == "_sd_delete", (
            f"CRUDBase.delete not rebound; got {crud_base_mod.CRUDBase.delete.__name__}"
        )
        # Reads are filtered globally — they must NOT be reassigned to _sd_* here.
        assert not crud_base_mod.CRUDBase.get.__name__.startswith("_sd_"), (
            "CRUDBase.get must NOT be rebound — reads are filtered by the global "
            f"do_orm_execute listener under SPEC-v2; got {crud_base_mod.CRUDBase.get.__name__}"
        )
        assert not crud_base_mod.CRUDBase.get_multi.__name__.startswith("_sd_"), (
            "CRUDBase.get_multi must NOT be rebound — reads are filtered by the "
            f"global filter; got {crud_base_mod.CRUDBase.get_multi.__name__}"
        )

        # The global read filter is the SPEC-v2 mechanism: importing the emitted
        # module registers a do_orm_execute listener on Session (INV-SD-01).
        from sqlalchemy import event
        from sqlalchemy.orm import Session

        from app.core import soft_delete_filter  # noqa: F401  (registers the listener)

        assert event.contains(
            Session, "do_orm_execute", soft_delete_filter._enforce_soft_delete_filter
        ), (
            "soft_delete_filter must register a do_orm_execute listener on Session "
            "(global read exclusion, INV-SD-01)."
        )
    finally:
        sys.path[:] = _orig_path


