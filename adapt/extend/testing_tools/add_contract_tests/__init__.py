"""TOOL-026: add_contract_tests — schemathesis + Pact contract tests for FastAPI.

Generates schemathesis property-based fuzzing tests against the OpenAPI schema
and Pact consumer/provider contract stubs showing the integration pattern.

The tool is idempotent: a second run returns ``status="no_op"`` when
``tests/contracts/`` already contains the fingerprint file.
"""

from __future__ import annotations

import ast
import time
from pathlib import Path

from adapt._base import render_to
from adapt.contracts import ToolInput, ToolResult, validate_project_dir
from adapt.contracts.prerequisites import Prereq, ensure_prerequisites

_HERE = Path(__file__).parent

MCP_TOOL = {
    "name": "fastapi_testing_add_contract_tests",
    "description": "Add consumer-driven contract tests using Pact or Schemathesis.",
    "tags": ["extend", "testing"],
    "entry": "add_contract_tests",
}


def add_contract_tests(
    inp: ToolInput,
    openapi_path: str = "/openapi.json",
    max_examples: int = 100,
    stateful: bool = False,
    exclude_endpoints: list[str] | None = None,
) -> ToolResult:
    """Generate schemathesis + Pact contract tests for a FastAPI project.

    Args:
        inp: ``ToolInput`` with ``project_dir`` and optional ``dry_run``.
        openapi_path: URL path for the OpenAPI JSON schema (default ``/openapi.json``).
        max_examples: Max Hypothesis examples per endpoint (default 100).
        stateful: When ``True``, enables link-based stateful sequence testing.
        exclude_endpoints: Paths to exclude from fuzzing (e.g. ``["/admin/wipe"]``).

    Returns:
        ``ToolResult`` with ``status``, ``files_created``, ``files_modified``,
        ``notes``, and ``next_steps``.
    """
    start = time.monotonic()
    project = Path(inp.project_dir)
    err = validate_project_dir(inp.project_dir)
    if err:
        return ToolResult(status="error", error=err, execution_time_ms=_ms(start))

    prereq_errors, scaffolded = ensure_prerequisites(
        inp.project_dir,
        Prereq.BASE_MODEL,
        auto_scaffold=not inp.dry_run,
    )
    if prereq_errors:
        return ToolResult(
            status="error",
            error="Prerequisites not met:\n" + "\n".join(f"  - {e}" for e in prereq_errors),
            notes=[
                "These prerequisites cannot be auto-created.",
                "Generate a base project first:",
                "  fastapi_generate_project(output_dir='...', profile='api', models={...})",
            ],
            execution_time_ms=_ms(start),
        )

    files_created: list[str] = list(scaffolded or [])
    contracts_dir = project / "tests" / "contracts"

    fingerprint = contracts_dir / "conftest.py"
    if fingerprint.exists() and "schemathesis" in fingerprint.read_text():
        return ToolResult(
            status="no_op",
            notes=["tests/contracts/conftest.py already contains schemathesis setup — skipped."],
            execution_time_ms=_ms(start),
        )

    if inp.dry_run:
        return ToolResult(
            status="success",
            notes=[
                "[dry_run] Would generate schemathesis + Pact contract tests.",
                f"[dry_run] openapi_path={openapi_path!r}, max_examples={max_examples}.",
                "[dry_run] No files written.",
            ],
            next_steps=["Re-run without dry_run=True to apply changes."],
            execution_time_ms=_ms(start),
        )

    excludes = exclude_endpoints or []
    files_modified: list[str] = []

    contracts_dir.mkdir(parents=True, exist_ok=True)
    pacts_dir = project / "pacts"
    pacts_dir.mkdir(exist_ok=True)
    ci_dir = project / ".github" / "workflows"
    ci_dir.mkdir(parents=True, exist_ok=True)

    init_file = contracts_dir / "__init__.py"
    init_file.write_text(
        '"""Contract test package generated by add_contract_tests (TOOL-026)."""\n'
    )
    files_created.append(str(init_file))

    conftest_file = contracts_dir / "conftest.py"
    _write_contracts_conftest(conftest_file, openapi_path)
    files_created.append(str(conftest_file))

    base_test = contracts_dir / "test_api_schema.py"
    _write_schemathesis_base(base_test, max_examples, excludes)
    files_created.append(str(base_test))

    stateful_test = contracts_dir / "test_stateful.py"
    _write_stateful_tests(stateful_test, stateful)
    files_created.append(str(stateful_test))

    checks_module = contracts_dir / "custom_checks.py"
    render_to(_HERE, "custom_checks.py.tmpl", dest=checks_module, substitutions={})
    files_created.append(str(checks_module))

    pact_file = contracts_dir / "test_pact_stubs.py"
    render_to(_HERE, "pact_stubs.py.tmpl", dest=pact_file, substitutions={})
    files_created.append(str(pact_file))

    exclude_yaml = project / ".schemathesis-exclude.yaml"
    _write_exclude_yaml(exclude_yaml, excludes)
    files_created.append(str(exclude_yaml))

    ci_file = ci_dir / "contract-tests.yml"
    _write_ci_workflow(ci_file, max_examples)
    files_created.append(str(ci_file))

    pyproject = project / "pyproject.toml"
    if pyproject.exists():
        _patch_pyproject(pyproject)
        files_modified.append(str(pyproject))

    for path_str in files_created:
        p = Path(path_str)
        if p.suffix == ".py" and p.is_file():
            try:
                ast.parse(p.read_text())
            except SyntaxError as exc:
                return ToolResult(
                    status="error",
                    error=f"Generated file has syntax error: {p}: {exc}",
                    execution_time_ms=_ms(start),
                )

    (project / "tests").mkdir(parents=True, exist_ok=True)
    emitted = project / "tests" / "test_add_contract_tests_emitted.py"
    if not emitted.exists():
        render_to(_HERE, "test_add_contract_tests_emitted.py.tmpl", dest=emitted, substitutions={})
        files_created.append(str(emitted))

    return ToolResult(
        status="success",
        files_created=files_created,
        files_modified=files_modified,
        notes=[
            "Schemathesis fuzz tests wired via schemathesis.from_asgi().",
            "Pact stubs show consumer/provider contract pattern (customize for real services).",
            f"Endpoints excluded from fuzzing: {excludes or ['(none)']!r}",
            f"Stateful sequence testing: {'enabled' if stateful else 'disabled (pass stateful=True to enable)'}",
        ],
        next_steps=[
            "pip install schemathesis pact-python hypothesis",
            "pytest tests/contracts/ -m schemathesis -v",
            "pytest tests/contracts/ -m pact_consumer -v",
            "Review .schemathesis-exclude.yaml and add any destructive endpoints.",
        ],
        execution_time_ms=_ms(start),
    )


def _write_contracts_conftest(dest: Path, openapi_path: str) -> None:
    content = (
        '"""Shared fixtures for contract tests (schemathesis + Pact).\n\n'
        "Generated by add_contract_tests tool (TOOL-026).\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "import pytest\n"
        "import schemathesis\n"
        "from fastapi.testclient import TestClient\n\n"
        "from app.main import app\n\n\n"
        '@pytest.fixture(scope="session")\n'
        "def schema():\n"
        '    """Load the OpenAPI schema once per test session."""\n'
        f'    return schemathesis.from_asgi("{openapi_path}", app)\n\n\n'
        '@pytest.fixture(scope="session")\n'
        "def api_client():\n"
        '    """Return a TestClient for direct HTTP calls in contract tests."""\n'
        "    with TestClient(app, raise_server_exceptions=False) as client:\n"
        "        yield client\n\n\n"
        '@pytest.fixture(scope="session")\n'
        "def auth_headers(api_client: TestClient) -> dict[str, str]:\n"
        '    """Obtain a valid JWT bearer token for contract tests."""\n'
        "    response = api_client.post(\n"
        '        "/api/v1/login/access-token",\n'
        '        data={"username": "test@example.com", "password": "changeme"},\n'
        "    )\n"
        "    if response.status_code == 200:\n"
        '        token = response.json().get("access_token", "")\n'
        '        return {"Authorization": f"Bearer {token}"}\n'
        "    return {}\n"
    )
    dest.write_text(content)


def _write_schemathesis_base(dest: Path, max_examples: int, excludes: list[str]) -> None:
    exclude_check = ""
    if excludes:
        exclude_list = repr(excludes)
        exclude_check = f"_EXCLUDED_PATHS: frozenset[str] = frozenset({exclude_list})\n\n"

    max_half = min(max_examples, 50)
    content = (
        '"""Schemathesis property-based contract tests.\n\n'
        "Generated by add_contract_tests tool (TOOL-026).\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "import schemathesis\n"
        "from hypothesis import settings\n"
        "from schemathesis import Case\n\n"
        "from tests.contracts.custom_checks import (  # noqa: F401\n"
        "    validate_error_response_structure,\n"
        "    validate_no_500_on_valid_input,\n"
        ")\n\n"
        f"{exclude_check}"
        'schema = schemathesis.from_pytest_fixture("schema")\n\n\n'
        "@schema.parametrize()\n"
        f"@settings(max_examples={max_examples}, deadline=5_000)\n"
        "def test_api_contract(case: Case, auth_headers: dict[str, str]) -> None:\n"
        '    """Fuzz every API endpoint and validate response contracts."""\n'
        "    case.headers = case.headers or {}\n"
        "    case.headers.update(auth_headers)\n"
        "    response = case.call_asgi()\n"
        "    case.validate_response(response)\n\n\n"
        '@schema.parametrize(method="GET")\n'
        f"@settings(max_examples={max_half}, deadline=5_000)\n"
        "def test_read_endpoints_never_500(case: Case, auth_headers: dict[str, str]) -> None:\n"
        '    """Assert GET endpoints never return 5xx on schema-valid inputs."""\n'
        "    case.headers = case.headers or {}\n"
        "    case.headers.update(auth_headers)\n"
        "    response = case.call_asgi()\n"
        "    assert response.status_code < 500, (\n"
        '        f"GET {case.formatted_path} returned {response.status_code}: "\n'
        '        f"{response.text[:200]}"\n'
        "    )\n"
    )
    dest.write_text(content)


def _write_stateful_tests(dest: Path, enabled: bool) -> None:
    if not enabled:
        content = (
            '"""Stateful schemathesis tests (disabled by default).\n\n'
            "Enable via: add_contract_tests(inp, stateful=True)\n\n"
            "Generated by add_contract_tests tool (TOOL-026).\n"
            '"""\n\n'
            "from __future__ import annotations\n\n"
            "import pytest\n"
            "import schemathesis\n"
            "from schemathesis import Case\n\n"
            'schema = schemathesis.from_pytest_fixture("schema")\n\n\n'
            '@pytest.mark.skip(reason="Stateful tests disabled — re-run with stateful=True to enable.")\n'
            "@schema.parametrize(stateful=schemathesis.Stateful.links)\n"
            "def test_stateful_api_sequence(case: Case, auth_headers: dict[str, str]) -> None:\n"
            '    """Chain API calls via OpenAPI response links for workflow testing."""\n'
            "    case.headers = case.headers or {}\n"
            "    case.headers.update(auth_headers)\n"
            "    response = case.call_asgi()\n"
            "    case.validate_response(response)\n"
        )
    else:
        content = (
            '"""Stateful schemathesis sequence tests.\n\n'
            "Generated by add_contract_tests tool (TOOL-026).\n"
            '"""\n\n'
            "from __future__ import annotations\n\n"
            "import schemathesis\n"
            "from schemathesis import Case\n\n"
            'schema = schemathesis.from_pytest_fixture("schema")\n\n\n'
            "@schema.parametrize(stateful=schemathesis.Stateful.links)\n"
            "def test_stateful_api_sequence(case: Case, auth_headers: dict[str, str]) -> None:\n"
            '    """Stateful test following OpenAPI response links."""\n'
            "    case.headers = case.headers or {}\n"
            "    case.headers.update(auth_headers)\n"
            "    response = case.call_asgi()\n"
            "    case.validate_response(response)\n"
        )
    dest.write_text(content)


def _write_exclude_yaml(dest: Path, excludes: list[str]) -> None:
    base_excludes = ["/admin/wipe", "/health", "/metrics"]
    all_excludes = sorted(set(base_excludes + excludes))
    exclude_lines = "\n".join(f"  - {e}  # excluded from fuzz testing" for e in all_excludes)
    content = (
        "# .schemathesis-exclude.yaml\n"
        "# Endpoints excluded from schemathesis property-based fuzzing.\n"
        "# Generated by add_contract_tests tool (TOOL-026).\n\n"
        "excluded_paths:\n"
        f"{exclude_lines}\n"
    )
    dest.write_text(content)


def _write_ci_workflow(dest: Path, max_examples: int) -> None:
    content = (
        "# .github/workflows/contract-tests.yml\n"
        "# Contract test CI pipeline — schemathesis + Pact.\n"
        "# Generated by add_contract_tests tool (TOOL-026).\n\n"
        "name: Contract Tests\n\n"
        "on:\n"
        "  pull_request:\n"
        "    branches: [main, develop]\n"
        "  push:\n"
        "    branches: [main]\n\n"
        "jobs:\n"
        "  schemathesis:\n"
        "    name: Schemathesis fuzz\n"
        "    runs-on: ubuntu-latest\n"
        "    steps:\n"
        "      - uses: actions/checkout@v4\n\n"
        "      - name: Set up Python\n"
        "        uses: actions/setup-python@v5\n"
        "        with:\n"
        '          python-version: "3.12"\n'
        "          cache: pip\n\n"
        "      - name: Install dependencies\n"
        "        run: |\n"
        '          pip install -e ".[test]"\n'
        "          pip install schemathesis hypothesis\n\n"
        "      - name: Run contract tests\n"
        "        run: |\n"
        "          pytest tests/contracts/ -m schemathesis -v \\\n"
        "            --hypothesis-seed=42 \\\n"
        f"            --hypothesis-settings=max_examples={max_examples}\n\n"
        "      - name: Upload schemathesis report\n"
        "        if: always()\n"
        "        uses: actions/upload-artifact@v4\n"
        "        with:\n"
        "          name: schemathesis-report\n"
        "          path: .hypothesis/\n"
    )
    dest.write_text(content)


def _patch_pyproject(pyproject_file: Path) -> None:
    src = pyproject_file.read_text()
    if "schemathesis" in src:
        return
    marker_block = (
        "\n\n# Contract test markers — added by add_contract_tests tool (TOOL-026)\n"
        "[tool.pytest.ini_options]\n"
        "markers = [\n"
        '    "schemathesis: schemathesis property-based API contract tests",\n'
        '    "pact_consumer: Pact consumer-side contract tests",\n'
        '    "pact_provider: Pact provider-side verification tests",\n'
        "]\n"
    )
    pyproject_file.write_text(src + marker_block)


def _ms(start: float) -> int:
    return int((time.monotonic() - start) * 1000)
