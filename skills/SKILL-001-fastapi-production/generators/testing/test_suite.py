# Field value factory — generates sensible test payloads from type hints
# ---------------------------------------------------------------------------

_SAMPLE_VALUES: dict[str, str] = {
    "str": '"test-value"',
    "text": '"A longer test value for text fields."',
    "int": "42",
    "float": "3.14",
    "bool": "True",
    "Decimal": '"9.99"',
    "decimal": '"9.99"',
    "date": '"2025-01-15"',
    "datetime": '"2025-01-15T12:00:00Z"',
    "EmailStr": '"test@example.com"',
    "email": '"test@example.com"',
    "url": '"https://example.com"',
    "password": '"SecurePass123!"',
    "uuid": '"00000000-0000-0000-0000-000000000001"',
}

_UPDATE_VALUES: dict[str, str] = {
    "str": '"updated-value"',
    "text": '"An updated text value."',
    "int": "99",
    "float": "6.28",
    "bool": "False",
    "Decimal": '"19.99"',
    "decimal": '"19.99"',
    "date": '"2025-06-01"',
    "datetime": '"2025-06-01T18:00:00Z"',
    "EmailStr": '"updated@example.com"',
    "email": '"updated@example.com"',
    "url": '"https://updated.example.com"',
    "password": '"NewSecurePass456!"',
    "uuid": '"00000000-0000-0000-0000-000000000002"',
}


def _build_payload(fields: dict[str, str], values: dict[str, str]) -> str:
    """Build a Python dict literal from a fields mapping."""
    items: list[str] = []
    for name, raw_type in fields.items():
        type_key = raw_type.rstrip("?")
        val = values.get(type_key, '"test"')
        items.append(f'    "{name}": {val},')
    return "{\n" + "\n".join(items) + "\n}"


