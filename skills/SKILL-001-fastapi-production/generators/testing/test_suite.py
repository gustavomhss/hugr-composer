"""Generator for test files that exercise every generated endpoint.

Generates pytest test modules for login, users, and CRUD model routes.
All tests use ``httpx.AsyncClient`` (provided by conftest.py) with
``pytest.mark.asyncio`` for async execution.

The generated tests are designed to work with the fixtures from
``generate_test_infrastructure()`` (conftest.py):
- ``client`` — httpx.AsyncClient wired to the FastAPI app
- ``superuser_token`` — dict ``{"Authorization": "Bearer ..."}``
- ``normal_user_token`` — dict ``{"Authorization": "Bearer ..."}``
"""

from __future__ import annotations

import re
import textwrap
from pathlib import Path


# ---------------------------------------------------------------------------
# Simple inflection (duplicated from crud_routes.py to stay self-contained)
# ---------------------------------------------------------------------------

_IRREGULAR: dict[str, str] = {
    "person": "people",
    "child": "children",
    "mouse": "mice",
    "goose": "geese",
    "ox": "oxen",
}


def _pluralize(word: str) -> str:
    """Return a naive English plural for *word*."""
    lower = word.lower()
    if lower in _IRREGULAR:
        plural = _IRREGULAR[lower]
        return word[0] + plural[1:] if word[0].isupper() else plural
    if re.search(r"(s|x|z|ch|sh)$", lower):
        return word + "es"
    if re.search(r"[^aeiou]y$", lower):
        return word[:-1] + "ies"
    return word + "s"


