def _generate_user_tests() -> str:
    return textwrap.dedent('''\
        """Tests for user endpoints (/users)."""

        from __future__ import annotations

        import pytest
        from httpx import AsyncClient

        from app.core.config import settings


        API = settings.API_V1_STR


        # -------------------------------------------------------------------
        # POST /users/signup
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_signup(client: AsyncClient) -> None:
            """Public signup creates a user and returns 201 without hashed_password."""
            payload = {
                "email": "newuser@example.com",
                "password": "StrongPass123!",
                "full_name": "New User",
            }
            response = await client.post(f"{API}/users/signup", json=payload)

            assert response.status_code == 201
            body = response.json()
            assert body["email"] == "newuser@example.com"
            assert "hashed_password" not in body


        @pytest.mark.asyncio
        async def test_signup_duplicate(client: AsyncClient) -> None:
            """Duplicate email returns 400."""
            payload = {
                "email": "duplicate@example.com",
                "password": "StrongPass123!",
                "full_name": "First User",
            }
            await client.post(f"{API}/users/signup", json=payload)

            # Second signup with same email
            response = await client.post(f"{API}/users/signup", json=payload)
            assert response.status_code == 400


        # -------------------------------------------------------------------
        # GET /users/me
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_get_me(
            client: AsyncClient,
            normal_user_token: dict[str, str],
        ) -> None:
            """Authenticated user can fetch their own profile."""
            response = await client.get(
                f"{API}/users/me",
                headers=normal_user_token,
            )

            assert response.status_code == 200
            body = response.json()
            assert "email" in body
            assert "id" in body


        # -------------------------------------------------------------------
        # PATCH /users/me
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_update_me(
            client: AsyncClient,
            normal_user_token: dict[str, str],
        ) -> None:
            """Authenticated user can update their own profile."""
            response = await client.patch(
                f"{API}/users/me",
                headers=normal_user_token,
                json={"full_name": "Updated Name"},
            )

            assert response.status_code == 200
            body = response.json()
            assert body["full_name"] == "Updated Name"


        # -------------------------------------------------------------------
        # PATCH /users/me/password
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_update_password(
            client: AsyncClient,
            normal_user_token: dict[str, str],
        ) -> None:
            """Authenticated user can change their password."""
            response = await client.patch(
                f"{API}/users/me/password",
                headers=normal_user_token,
                json={
                    "current_password": "testpassword123",
                    "new_password": "NewSecurePass456!",
                },
            )

            assert response.status_code == 200
            body = response.json()
            assert body["message"] == "Password updated successfully"


        @pytest.mark.asyncio
        async def test_update_password_wrong_current(
            client: AsyncClient,
            normal_user_token: dict[str, str],
        ) -> None:
            """Wrong current password returns 400."""
            response = await client.patch(
                f"{API}/users/me/password",
                headers=normal_user_token,
                json={
                    "current_password": "wrong-password",
                    "new_password": "NewSecurePass456!",
                },
            )

            assert response.status_code == 400


        # -------------------------------------------------------------------
        # GET /users/ (superuser only)
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_list_users_superuser(
            client: AsyncClient,
            superuser_token: dict[str, str],
        ) -> None:
            """Superuser can list all users."""
            response = await client.get(
                f"{API}/users/",
                headers=superuser_token,
            )

            assert response.status_code == 200
            body = response.json()
            assert "data" in body
            assert "count" in body
            assert isinstance(body["data"], list)


        @pytest.mark.asyncio
        async def test_list_users_regular(
            client: AsyncClient,
            normal_user_token: dict[str, str],
        ) -> None:
            """Regular user cannot list all users (403)."""
            response = await client.get(
                f"{API}/users/",
                headers=normal_user_token,
            )

            assert response.status_code == 403
    ''')


