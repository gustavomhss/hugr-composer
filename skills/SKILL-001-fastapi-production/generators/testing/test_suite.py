def _generate_login_tests() -> str:
    return textwrap.dedent('''\
        """Tests for authentication endpoints (/login)."""

        from __future__ import annotations

        import pytest
        from httpx import AsyncClient

        from app.core.config import settings


        API = settings.API_V1_STR


        # -------------------------------------------------------------------
        # POST /login/access-token
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_login_success(
            client: AsyncClient,
            superuser_token: dict[str, str],
        ) -> None:
            """Valid credentials return 200 with an access_token."""
            login_data = {
                "username": settings.FIRST_SUPERUSER_EMAIL,
                "password": "testpassword123",
            }
            response = await client.post(f"{API}/login/access-token", data=login_data)

            assert response.status_code == 200
            body = response.json()
            assert "access_token" in body
            assert body["access_token"]


        @pytest.mark.asyncio
        async def test_login_wrong_password(
            client: AsyncClient,
            superuser_token: dict[str, str],
        ) -> None:
            """Wrong password returns 401."""
            login_data = {
                "username": settings.FIRST_SUPERUSER_EMAIL,
                "password": "wrong-password",
            }
            response = await client.post(f"{API}/login/access-token", data=login_data)

            assert response.status_code == 401


        @pytest.mark.asyncio
        async def test_login_nonexistent_user(client: AsyncClient) -> None:
            """Non-existent email returns 401."""
            login_data = {
                "username": "nobody@example.com",
                "password": "doesnotmatter",
            }
            response = await client.post(f"{API}/login/access-token", data=login_data)

            assert response.status_code == 401


        # -------------------------------------------------------------------
        # POST /login/test-token
        # -------------------------------------------------------------------


        @pytest.mark.asyncio
        async def test_test_token(
            client: AsyncClient,
            superuser_token: dict[str, str],
        ) -> None:
            """Valid token returns 200 with user info."""
            response = await client.post(
                f"{API}/login/test-token",
                headers=superuser_token,
            )

            assert response.status_code == 200
            body = response.json()
            assert "email" in body
            assert "id" in body


        @pytest.mark.asyncio
        async def test_test_token_no_auth(client: AsyncClient) -> None:
            """Missing token returns 401."""
            response = await client.post(f"{API}/login/test-token")

            assert response.status_code == 401
    ''')


