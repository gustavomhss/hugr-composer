def generate_test_suite(
    output_dir: str,
    models: dict[str, dict[str, str]] | None = None,
    owner_models: dict[str, str] | None = None,
    with_auth: bool = True,
) -> dict:
    """Generate test files for login, user, and CRUD model endpoints.

    Produces test modules that work with the conftest.py generated by
    ``generate_test_infrastructure()``.  Every test uses
    ``pytest.mark.asyncio`` and ``httpx.AsyncClient``.

    Args:
        output_dir: Project root.  Files are written to
            ``tests/api/routes/``.
        models: Domain models dict — ``{"Product": {"name": "str", ...}}``.
            A ``test_{model_lower}.py`` file is generated for each.
        owner_models: Which models have owner-scoped access.
            ``{"Product": "user"}`` means the model has ``owner_id``.
        with_auth: Generate login and user test files.

    Returns:
        Dict with ``files_created`` and ``notes``.
    """
    out = Path(output_dir) / "tests"
    out.mkdir(parents=True, exist_ok=True)

    api_dir = out / "api"
    api_dir.mkdir(parents=True, exist_ok=True)

    routes_dir = api_dir / "routes"
    routes_dir.mkdir(parents=True, exist_ok=True)

    files: list[str] = []
    notes: list[str] = []

    # --- Package init files ---
    for pkg_dir in [api_dir, routes_dir]:
        init_file = pkg_dir / "__init__.py"
        if not init_file.exists():
            init_file.write_text("")
            files.append(str(init_file))

    # --- Login tests ---
    if with_auth:
        login_path = routes_dir / "test_login.py"
        login_path.write_text(_generate_login_tests())
        files.append(str(login_path))
        notes.append("Generated tests/api/routes/test_login.py with 5 login/token tests.")

    # --- User tests ---
    if with_auth:
        users_path = routes_dir / "test_users.py"
        users_path.write_text(_generate_user_tests())
        files.append(str(users_path))
        notes.append("Generated tests/api/routes/test_users.py with 8 user endpoint tests.")

    # --- CRUD model tests ---
    if models:
        for model_name, fields in models.items():
            has_owner = model_name in (owner_models or {})
            model_path = routes_dir / f"test_{model_name.lower()}.py"
            model_path.write_text(
                _generate_crud_tests(model_name, fields, has_owner)
            )
            files.append(str(model_path))
            notes.append(
                f"Generated tests/api/routes/test_{model_name.lower()}.py "
                f"with 6 CRUD tests for {model_name}."
            )

    return {"files_created": files, "notes": notes}


