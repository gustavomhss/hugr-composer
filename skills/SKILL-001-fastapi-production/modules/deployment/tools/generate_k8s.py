def _service_yaml(app_name: str, port: int) -> str:
    """Generate a ClusterIP Service manifest."""
    return textwrap.dedent(f"""\
        # Generated by SKILL-001 Deployment Module
        apiVersion: v1
        kind: Service
        metadata:
          name: {app_name}
          labels:
            app: {app_name}
        spec:
          type: ClusterIP
          selector:
            app: {app_name}
          ports:
          - name: http
            port: 80
            targetPort: {port}
            protocol: TCP
    """)


