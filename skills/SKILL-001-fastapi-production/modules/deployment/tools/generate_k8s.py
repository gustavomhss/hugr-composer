def _deployment_yaml(
    app_name: str,
    image: str,
    replicas: int,
    port: int,
    env_vars: dict[str, str] | None,
    cpu_request: str,
    cpu_limit: str,
    memory_request: str,
    memory_limit: str,
    prestop_sleep: int,
    termination_grace: int,
    graceful_shutdown_timeout: int,
) -> str:
    """Generate a Deployment manifest with SOTA zero-downtime patterns."""
    # Build env section from env_vars dict
    env_section = ""
    if env_vars:
        env_lines = []
        for key, value in sorted(env_vars.items()):
            env_lines.append(f"        - name: {key}")
            env_lines.append(f'          value: "{value}"')
        env_section = "\n".join(env_lines)

    env_block = ""
    if env_section:
        env_block = f"""
        env:
{env_section}"""

    return textwrap.dedent(f"""\
        # Generated by SKILL-001 Deployment Module
        # Zero-downtime rolling update with 3-level probes
        apiVersion: apps/v1
        kind: Deployment
        metadata:
          name: {app_name}
          labels:
            app: {app_name}
        spec:
          replicas: {replicas}
          revisionHistoryLimit: 5
          selector:
            matchLabels:
              app: {app_name}
          strategy:
            type: RollingUpdate
            rollingUpdate:
              maxSurge: 1            # Create 1 extra pod during update
              maxUnavailable: 0      # NEVER fewer than desired replicas
          template:
            metadata:
              labels:
                app: {app_name}
            spec:
              terminationGracePeriodSeconds: {termination_grace}
              securityContext:
                runAsNonRoot: true
                runAsUser: 10001
                runAsGroup: 10001
                fsGroup: 10001
              containers:
              - name: {app_name}
                image: {image}
                imagePullPolicy: IfNotPresent
                ports:
                - name: http
                  containerPort: {port}
                  protocol: TCP{env_block}
                envFrom:
                - configMapRef:
                    name: {app_name}-config
                    optional: true
                - secretRef:
                    name: {app_name}-secrets
                    optional: true
                resources:
                  requests:
                    cpu: "{cpu_request}"
                    memory: "{memory_request}"
                  limits:
                    cpu: "{cpu_limit}"
                    memory: "{memory_limit}"

                # --- 3-level probes ---
                # Liveness: process alive? NEVER check DB/Redis here
                livenessProbe:
                  httpGet:
                    path: /healthz
                    port: {port}
                  initialDelaySeconds: 0
                  periodSeconds: 15
                  timeoutSeconds: 3
                  failureThreshold: 3

                # Readiness: can accept traffic? Check ALL dependencies
                readinessProbe:
                  httpGet:
                    path: /readyz
                    port: {port}
                  initialDelaySeconds: 5
                  periodSeconds: 10
                  timeoutSeconds: 5
                  failureThreshold: 2

                # Startup: init complete? Disables liveness/readiness until success
                startupProbe:
                  httpGet:
                    path: /startupz
                    port: {port}
                  initialDelaySeconds: 0
                  periodSeconds: 5
                  timeoutSeconds: 3
                  failureThreshold: 30   # 30 * 5s = 150s max startup time

                # --- Zero-downtime: preStop hook ---
                # Sleep gives kube-proxy/LB time to deregister endpoints
                lifecycle:
                  preStop:
                    exec:
                      command: ["sh", "-c", "sleep {prestop_sleep}"]

                securityContext:
                  allowPrivilegeEscalation: false
                  readOnlyRootFilesystem: true
                  capabilities:
                    drop:
                      - ALL
    """)


