def _hpa_yaml(
    app_name: str,
    min_replicas: int,
    max_replicas: int,
    cpu_target: int,
    memory_target: int,
) -> str:
    """Generate an HPA manifest with CPU/memory metrics and stabilization policies."""
    return textwrap.dedent(f"""\
        # Generated by SKILL-001 Deployment Module
        # CPU target 70% leaves headroom for spikes during scale-up lag
        apiVersion: autoscaling/v2
        kind: HorizontalPodAutoscaler
        metadata:
          name: {app_name}-hpa
          labels:
            app: {app_name}
        spec:
          scaleTargetRef:
            apiVersion: apps/v1
            kind: Deployment
            name: {app_name}
          minReplicas: {min_replicas}
          maxReplicas: {max_replicas}
          metrics:
          - type: Resource
            resource:
              name: cpu
              target:
                type: Utilization
                averageUtilization: {cpu_target}
          - type: Resource
            resource:
              name: memory
              target:
                type: Utilization
                averageUtilization: {memory_target}
          behavior:
            scaleUp:
              stabilizationWindowSeconds: 60      # Prevent rapid scale-up flapping
              policies:
              - type: Pods
                value: 2                           # Add max 2 pods per event
                periodSeconds: 60
            scaleDown:
              stabilizationWindowSeconds: 300     # 5min cooldown before scale-down
              policies:
              - type: Pods
                value: 1                           # Remove max 1 pod per event
                periodSeconds: 120
    """)


