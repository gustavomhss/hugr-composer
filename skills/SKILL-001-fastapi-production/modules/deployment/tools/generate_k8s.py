"""
SKILL-001 Deployment Tool: Generate production-grade Kubernetes manifests.

Generates a complete set of K8s manifests for a FastAPI application with
SOTA patterns: zero-downtime rolling updates (maxSurge=1, maxUnavailable=0),
3-level probes (liveness/readiness/startup), preStop hook for connection
draining, HPA with scale-up/down stabilization, PDB, resource limits,
security context, and ConfigMap/Secret references.

Generated manifests:
    deployment.yaml  — Deployment with rolling update, probes, preStop, security context
    service.yaml     — ClusterIP Service with named port
    hpa.yaml         — HorizontalPodAutoscaler with CPU/memory metrics and behavior policies
    pdb.yaml         — PodDisruptionBudget with minAvailable
"""

