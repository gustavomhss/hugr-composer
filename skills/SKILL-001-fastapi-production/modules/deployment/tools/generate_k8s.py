def _pdb_yaml(app_name: str, min_available: int) -> str:
    """Generate a PodDisruptionBudget manifest."""
    return textwrap.dedent(f"""\
        # Generated by SKILL-001 Deployment Module
        # Ensures at least {min_available} pod(s) remain during voluntary disruptions
        # (node drain, cluster upgrades). Does NOT protect against node crashes.
        apiVersion: policy/v1
        kind: PodDisruptionBudget
        metadata:
          name: {app_name}-pdb
          labels:
            app: {app_name}
        spec:
          minAvailable: {min_available}
          selector:
            matchLabels:
              app: {app_name}
    """)


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------


def _validate_config(
    app_name: str,
    replicas: int,
    min_available: int,
    min_replicas: int,
    max_replicas: int,
    prestop_sleep: int,
    termination_grace: int,
) -> list[Finding]:
    """Validate configuration and return findings for anti-patterns."""
    findings: list[Finding] = []

    if replicas < 2:
        findings.append(Finding(
            rule_id="DEPLOY-001",
            severity=Severity.HIGH,
            title="Single replica deployment",
            description=(
                f"replicas={replicas}. A single replica means zero capacity "
                "during pod restarts, deploys, and node failures. Use at least 2."
            ),
            fix_suggestion="Set replicas to at least 2 for production.",
        ))

    if min_available >= replicas:
        findings.append(Finding(
            rule_id="DEPLOY-002",
            severity=Severity.CRITICAL,
            title="PDB minAvailable equals or exceeds replica count",
            description=(
                f"minAvailable={min_available} with replicas={replicas}. "
                "This blocks ALL voluntary evictions — kubectl drain will hang "
                "forever and node upgrades become impossible."
            ),
            fix_suggestion=f"Set minAvailable to {max(1, replicas - 1)} or lower.",
        ))

    if prestop_sleep >= termination_grace:
        findings.append(Finding(
            rule_id="DEPLOY-003",
            severity=Severity.HIGH,
            title="preStop sleep exceeds terminationGracePeriodSeconds",
            description=(
                f"preStop sleep={prestop_sleep}s but terminationGracePeriodSeconds="
                f"{termination_grace}s. Kubernetes will SIGKILL the container "
                "before the sleep finishes, defeating the purpose of graceful drain."
            ),
            fix_suggestion=(
                f"Set terminationGracePeriodSeconds to at least "
                f"{prestop_sleep + 35} (preStop + graceful shutdown + buffer)."
            ),
        ))

    if min_replicas < 2:
        findings.append(Finding(
            rule_id="DEPLOY-004",
            severity=Severity.MEDIUM,
            title="HPA minReplicas is 1",
            description=(
                f"minReplicas={min_replicas}. With a single replica during low "
                "traffic, any pod failure means zero capacity until HPA scales up."
            ),
            fix_suggestion="Set HPA minReplicas to at least 2.",
        ))

    if max_replicas <= min_replicas:
        findings.append(Finding(
            rule_id="DEPLOY-005",
            severity=Severity.HIGH,
            title="HPA maxReplicas not greater than minReplicas",
            description=(
                f"maxReplicas={max_replicas}, minReplicas={min_replicas}. "
                "HPA has no room to scale — it is effectively disabled."
            ),
            fix_suggestion="Set maxReplicas to at least 2x minReplicas.",
        ))

    return findings


