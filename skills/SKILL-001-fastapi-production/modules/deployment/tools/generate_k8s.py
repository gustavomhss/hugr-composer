def generate_k8s_manifests(
    app_name: str,
    image: str,
    replicas: int = 3,
    port: int = 8000,
    env_vars: dict[str, str] | None = None,
    with_hpa: bool = True,
    with_pdb: bool = True,
    *,
    cpu_request: str = "200m",
    cpu_limit: str = "500m",
    memory_request: str = "256Mi",
    memory_limit: str = "512Mi",
    cpu_target: int = 70,
    memory_target: int = 80,
    min_replicas: int = 2,
    max_replicas: int = 10,
    min_available: int = 1,
    prestop_sleep: int = 10,
    termination_grace: int = 45,
    graceful_shutdown_timeout: int = 30,
) -> dict[str, str]:
    """
    Generate production-grade Kubernetes manifests for a FastAPI application.

    Creates a complete set of K8s YAML manifests with zero-downtime rolling
    update strategy, 3-level health probes (liveness/readiness/startup),
    preStop hook for connection draining, resource limits, security context
    (non-root, read-only FS, drop all capabilities), HPA with stabilization
    policies, and PDB for disruption protection.

    Args:
        app_name: Application name used for metadata, labels, and selectors.
        image: Container image reference (e.g., "ghcr.io/org/myapi:v1.2.3").
        replicas: Number of desired pod replicas (default: 3).
        port: Container port the app listens on (default: 8000).
        env_vars: Optional dict of environment variables to inject.
        with_hpa: Generate HorizontalPodAutoscaler manifest (default: True).
        with_pdb: Generate PodDisruptionBudget manifest (default: True).
        cpu_request: CPU request for scheduler reservation (default: "200m").
        cpu_limit: CPU limit / throttle ceiling (default: "500m").
        memory_request: Memory request for scheduler reservation (default: "256Mi").
        memory_limit: Memory limit / OOMKill threshold (default: "512Mi").
        cpu_target: HPA CPU utilization target percentage (default: 70).
        memory_target: HPA memory utilization target percentage (default: 80).
        min_replicas: HPA minimum replicas (default: 2).
        max_replicas: HPA maximum replicas (default: 10).
        min_available: PDB minAvailable pods during disruption (default: 1).
        prestop_sleep: Seconds to sleep in preStop hook (default: 10).
        termination_grace: terminationGracePeriodSeconds (default: 45).
        graceful_shutdown_timeout: Uvicorn graceful shutdown timeout (default: 30).

    Returns:
        Dict mapping filename to YAML content string. Keys:
        "deployment.yaml", "service.yaml", and optionally "hpa.yaml", "pdb.yaml".

        Also includes a "findings" key with a list of Finding dicts for any
        detected configuration anti-patterns.

    Example::

        manifests = generate_k8s_manifests(
            app_name="billing-api",
            image="ghcr.io/myorg/billing-api:v2.1.0",
            replicas=3,
            port=8000,
            env_vars={"LOG_LEVEL": "info"},
        )
        for filename, content in manifests.items():
            if filename != "findings":
                Path(filename).write_text(content)
    """
    # Validate and collect findings
    findings = _validate_config(
        app_name=app_name,
        replicas=replicas,
        min_available=min_available,
        min_replicas=min_replicas,
        max_replicas=max_replicas,
        prestop_sleep=prestop_sleep,
        termination_grace=termination_grace,
    )

    result: dict[str, str] = {}

    result["deployment.yaml"] = _deployment_yaml(
        app_name=app_name,
        image=image,
        replicas=replicas,
        port=port,
        env_vars=env_vars,
        cpu_request=cpu_request,
        cpu_limit=cpu_limit,
        memory_request=memory_request,
        memory_limit=memory_limit,
        prestop_sleep=prestop_sleep,
        termination_grace=termination_grace,
        graceful_shutdown_timeout=graceful_shutdown_timeout,
    )

    result["service.yaml"] = _service_yaml(app_name, port)

    if with_hpa:
        result["hpa.yaml"] = _hpa_yaml(
            app_name=app_name,
            min_replicas=min_replicas,
            max_replicas=max_replicas,
            cpu_target=cpu_target,
            memory_target=memory_target,
        )

    if with_pdb:
        result["pdb.yaml"] = _pdb_yaml(app_name, min_available)

    # Attach findings as serializable dicts
    result["findings"] = [f.model_dump() for f in findings]  # type: ignore[assignment]

    return result
