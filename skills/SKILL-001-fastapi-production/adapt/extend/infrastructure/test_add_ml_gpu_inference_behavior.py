# ---------------------------------------------------------------------------
# QUALITY-06: torch NOT at top-level in any generated app/ file
# ---------------------------------------------------------------------------

def test_b06_torch_not_top_level_in_app(project_dir: Path) -> None:
    """B-06: torch must NOT appear in module-level imports in any app/ .py file.

    Verifies the lazy import contract programmatically — the core invariant
    of this tool.
    """
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        source = py_file.read_text()
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue
        for node in tree.body:  # Only top-level statements
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "torch" or alias.name.startswith("torch."):
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:"
                            f"{node.lineno}: import torch"
                        )
            elif isinstance(node, ast.ImportFrom) and node.module:
                if node.module == "torch" or node.module.startswith("torch."):
                    violations.append(
                        f"{py_file.relative_to(project_dir)}:"
                        f"{node.lineno}: from torch import ..."
                    )

    assert not violations, (
        "torch found at module top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


# ---------------------------------------------------------------------------
# QUALITY-07: All generated functions ≤ 50 LOC
# ---------------------------------------------------------------------------

def test_b07_no_function_over_50_loc(project_dir: Path) -> None:
    """B-07: No generated function in app/ may exceed 50 LOC."""
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if node.end_lineno:
                    loc = node.end_lineno - node.lineno + 1
                    if loc > 50:
                        violations.append(
                            f"{py_file.relative_to(project_dir)}: "
                            f"{node.name}() = {loc} LOC (limit 50)"
                        )

    assert not violations, (
        "Functions exceeding 50 LOC:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


