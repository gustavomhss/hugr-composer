def test_b08_config_fields_4_space_indent(project_dir: Path) -> None:
    """B-08: GPU config fields must be inside the Settings class body (4-space indent)."""
    config_file = project_dir / "app" / "core" / "config.py"
    assert config_file.exists(), "app/core/config.py not found"
    content = config_file.read_text()

    for field_name in ("GPU_ENABLED", "GPU_DEVICE_ID", "GPU_MEMORY_THRESHOLD_PCT",
                       "GPU_MIXED_PRECISION"):
        assert field_name in content, f"{field_name} missing from config.py"
        for line in content.splitlines():
            if field_name in line and ":" in line and ("=" in line or "bool" in line
                                                       or "int" in line or "float" in line):
                assert line.startswith("    "), (
                    f"{field_name} not at 4-space indent (not inside Settings class): {line!r}"
                )
                break


