# ---------------------------------------------------------------------------
# BEHAVIOR-10: psutil is NOT imported at top-level in any app/ file
# ---------------------------------------------------------------------------

def test_b10_psutil_not_imported_at_top_level(project_dir: Path) -> None:
    """B-10: psutil must NOT appear in top-level imports in any app/ .py file.

    psutil is expensive to import (spawns /proc reads on Linux) and should
    only be imported lazily inside the check functions, never at module level.
    """
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        source = py_file.read_text()
        try:
            tree = ast.parse(source)
        except SyntaxError:
            continue  # Syntax errors caught elsewhere

        for node in ast.walk(tree):
            # Only inspect top-level statements (not inside functions/classes)
            if not isinstance(node, ast.Module):
                continue
            for child in node.body:
                if isinstance(child, ast.Import):
                    for alias in child.names:
                        if alias.name == "psutil" or alias.name.startswith("psutil."):
                            violations.append(
                                f"{py_file.relative_to(project_dir)}:"
                                f"{child.lineno}: import psutil"
                            )
                elif isinstance(child, ast.ImportFrom):
                    if child.module and (
                        child.module == "psutil"
                        or child.module.startswith("psutil.")
                    ):
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:"
                            f"{child.lineno}: from psutil import ..."
                        )

    assert not violations, (
        "psutil found at top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


