def _get(asgi_app: Any, path: str) -> httpx.Response:
    """Issue a GET request against the ASGI app synchronously via anyio."""

    async def _call() -> httpx.Response:
        transport = httpx.ASGITransport(app=asgi_app)
        async with httpx.AsyncClient(
            transport=transport, base_url="http://test"
        ) as client:
            return await client.get(path)

    return anyio.from_thread.run_sync(anyio.run, _call)


def _get_async(asgi_app: Any, path: str) -> httpx.Response:
    """Issue an async GET using anyio.run (works outside event loop)."""

    async def _call() -> httpx.Response:
        transport = httpx.ASGITransport(app=asgi_app)
        async with httpx.AsyncClient(
            transport=transport, base_url="http://test"
        ) as client:
            return await client.get(path)

    return anyio.run(_call)


