def _patch_project(project_dir: Path) -> None:
    """Apply SQLite + idempotency stubs to the fixture project."""
    (project_dir / "app" / "core" / "db.py").write_text(_SQLITE_DB_PY)
    (project_dir / "app" / "middleware" / "idempotency.py").write_text(
        _PASSTHROUGH_IDEMPOTENCY_PY
    )


def _load_app(project_dir: Path) -> Any:
    """Load ``app.main:app`` from *project_dir* in an isolated sys.path context.

    The project's ``app/`` package is loaded via importlib so each test
    fixture gets a fresh module namespace, avoiding cross-test state leakage.
    """
    # Prepend project_dir so ``import app`` resolves there
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))

    # Evict any stale 'app' modules so we always reload from project_dir
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]

    try:
        app_module = importlib.import_module("app.main")
    finally:
        # Restore sys.path after import (module stays in sys.modules for test)
        sys.path[:] = _orig_path

    return app_module.app


def _setup_project() -> tuple[Path, Any]:
    """Create, patch, apply tool, and load app. Returns (project_dir, asgi_app)."""
    project_dir = create_fixture_project(name="health_behavior")

    # Apply the tool BEFORE patching so it writes the real generated files
    result = add_health_deep(ToolInput(project_dir=str(project_dir)))
    assert result.status == "success", (
        f"add_health_deep failed: {result.error}\nnotes: {result.notes}"
    )

    # Now patch db + idempotency for test isolation
    _patch_project(project_dir)

    # Register the generated health_deep router into main.py's app.
    # The tool patches main.py with an import but does NOT call include_router.
    # We do it explicitly here at the module level so the ASGI app has the routes.
    asgi_app = _load_app(project_dir)

    return project_dir, asgi_app


