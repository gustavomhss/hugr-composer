# BEHAVIOR-04: POST /refunds/webhook/stripe without sig → 400 or 422 or ModuleNotFoundError
# ---------------------------------------------------------------------------

@pytest.mark.anyio
async def test_b04_webhook_without_signature_returns_400(asgi_app: Any) -> None:
    """B-04: POST /refunds/webhook/stripe without sig returns 400 or raises ModuleNotFoundError.

    When the ``stripe`` SDK is installed:
      - valid sig absent → 400 (stripe.Webhook.construct_event raises)
    When the ``stripe`` SDK is NOT installed:
      - the lazy ``import stripe`` raises ``ModuleNotFoundError`` which
        propagates as an unhandled server error.

    Both outcomes confirm the webhook route exists and the lazy import guard
    is in place — the route is NOT available without the SDK, as designed.
    """
    transport = httpx.ASGITransport(app=asgi_app, raise_app_exceptions=False)
    try:
        async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
            response = await client.post(
                "/api/v1/refunds/webhook/stripe",
                content=b'{"type": "charge.refund.updated"}',
                headers={"content-type": "application/json"},
            )
        # stripe installed: sig verification fails → 400; or unhandled error → 500
        assert response.status_code in (400, 422, 500), (
            f"Expected 400/422/500 for missing signature, "
            f"got {response.status_code}; body: {response.text}"
        )
    except ModuleNotFoundError as exc:
        # stripe SDK not installed — this is expected in CI without stripe
        assert "stripe" in str(exc).lower(), (
            f"Unexpected ModuleNotFoundError: {exc}"
        )


