# BEHAVIOR-05: app/models/refund.py is valid Python with correct structure
# ---------------------------------------------------------------------------

def test_b05_refund_model_ast_structure(project_dir: Path) -> None:
    """B-05: app/models/refund.py must have correct AST structure at runtime.

    SQLAlchemy ORM models with ``from __future__ import annotations`` cannot
    be exec'd in isolation (SQLAlchemy needs the full module graph for
    annotation resolution).  We verify structure via AST instead.
    """
    model_file = project_dir / "app" / "models" / "refund.py"
    assert model_file.exists(), "app/models/refund.py not found"

    content = model_file.read_text()
    tree = ast.parse(content)

    # Verify class Refund is declared at module level
    class_names = [
        node.name for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef)
    ]
    assert "Refund" in class_names, (
        f"class Refund not found in app/models/refund.py; classes: {class_names}"
    )

    # Verify it has the required annotated columns
    refund_fields: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Refund":
            for item in node.body:
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    refund_fields.append(item.target.id)

    for required_field in [
        "id", "payment_id", "stripe_refund_id", "amount_cents",
        "status", "requested_by", "created_at",
    ]:
        assert required_field in refund_fields, (
            f"Required field '{required_field}' not in Refund model; "
            f"found: {refund_fields}"
        )


