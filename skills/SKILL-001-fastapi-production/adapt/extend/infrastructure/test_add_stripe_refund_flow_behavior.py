# ---------------------------------------------------------------------------
# BEHAVIOR-08: stripe NOT at module top-level in any generated app/ file
# ---------------------------------------------------------------------------

def test_b08_stripe_not_at_module_top_level(project_dir: Path) -> None:
    """B-08: stripe must NOT be imported at module top-level in any app/ file."""
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue

        for node in tree.body:
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == "stripe" or alias.name.startswith("stripe."):
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:"
                            f"{node.lineno}: import stripe"
                        )
            elif isinstance(node, ast.ImportFrom):
                if node.module and (
                    node.module == "stripe" or node.module.startswith("stripe.")
                ):
                    violations.append(
                        f"{py_file.relative_to(project_dir)}:"
                        f"{node.lineno}: from stripe import ..."
                    )

    assert not violations, (
        "stripe found at top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


