# ---------------------------------------------------------------------------
# B-07: lazy SDK imports verified by AST walk
# ---------------------------------------------------------------------------

def test_b07_no_top_level_optional_sdk_imports(project_dir: Path) -> None:
    """B-07: No optional SDK imports at module level in generated resilience files."""
    resilience_dir = project_dir / "app" / "resilience"
    # No optional SDKs for retry budget — just stdlib
    optional_sdks = {"redis", "stripe", "boto3", "aiohttp", "celery"}
    violations: list[str] = []
    for py_file in sorted(resilience_dir.rglob("*.py")):
        tree = ast.parse(py_file.read_text())
        for node in tree.body:
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                names = []
                if isinstance(node, ast.Import):
                    names = [alias.name.split(".")[0] for alias in node.names]
                else:
                    names = [node.module.split(".")[0]] if node.module else []
                for name in names:
                    if name in optional_sdks:
                        violations.append(f"{py_file.name}: top-level import {name!r}")
    assert not violations, "Top-level optional SDK imports:\n" + "\n".join(violations)


# ---------------------------------------------------------------------------
# B-08: ruff F401 clean — no dead imports in generated files
# ---------------------------------------------------------------------------

def test_b08_no_dead_imports_in_generated_files(project_dir: Path) -> None:
    """B-08: Verify no obviously dead imports via AST analysis."""
    resilience_dir = project_dir / "app" / "resilience"
    # Verify each file's imports are used (basic check: import name appears in body)
    for py_file in sorted(resilience_dir.rglob("*.py")):
        source = py_file.read_text()
        tree = ast.parse(source)
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom):
                # Skip __future__ imports — 'annotations' is not used by name
                if node.module == "__future__":
                    continue
                if node.names:
                    for alias in node.names:
                        name = alias.asname or alias.name
                        if name == "*":
                            continue
                        # Count occurrences outside the import line itself
                        lines_using = [
                            ln for ln in source.splitlines()
                            if name in ln and "import" not in ln
                        ]
                        assert len(lines_using) >= 1 or name.startswith("_"), (
                            f"{py_file.name}: imported {name!r} appears unused"
                        )


