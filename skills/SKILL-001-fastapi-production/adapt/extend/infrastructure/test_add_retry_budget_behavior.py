def test_b04_budget_exhausted_error_raised(project_dir: Path) -> None:
    """B-04: BudgetExhaustedError raised when retry ratio exceeds budget."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.resilience.retry_budget import RetryBudget, BudgetExhaustedError
        # Very tight budget: 0% retries allowed after warm-up
        budget = RetryBudget("tight_svc", ratio=0.0, window_s=60.0, min_requests=1)
        budget.record_request()
        budget.record_retry()
        # Now budget should be exhausted
        assert budget.can_retry() is False
    except ImportError as exc:
        raise AssertionError(f"Could not import retry_budget: {exc}") from exc
    finally:
        sys.path[:] = _orig_path


