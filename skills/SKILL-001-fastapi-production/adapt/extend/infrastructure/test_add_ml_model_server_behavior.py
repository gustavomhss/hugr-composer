# BEHAVIOR-07: All generated app/ functions ≤ 50 LOC (CC-07 / INV-05)
# ---------------------------------------------------------------------------

def test_b07_all_functions_le_50_loc(project_dir: Path) -> None:
    """B-07: Every function in generated app/ is ≤ 50 LOC."""
    app_dir = project_dir / "app"
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if hasattr(node, "end_lineno") and node.end_lineno:
                    loc = node.end_lineno - node.lineno + 1
                    if loc > 50:
                        violations.append(
                            f"{py_file.relative_to(project_dir)}: "
                            f"def {node.name} at line {node.lineno} has {loc} LOC (limit: 50)"
                        )

    assert not violations, (
        "Functions exceeding 50 LOC:\n" + "\n".join(f"  {v}" for v in violations)
    )


