    if result.returncode != 0 and "F401" in result.stdout:
        # Filter to only the generated ML files to avoid pre-existing issues
        ml_violations = [
            line for line in result.stdout.splitlines()
            if "app/ml/" in line or "app/schemas/ml" in line or "app/api/routes/ml" in line
        ]
        assert not ml_violations, (
            "Unused imports (F401) in generated ML files:\n"
            + "\n".join(ml_violations)
        )


