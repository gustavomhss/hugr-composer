# BEHAVIOR-06: No ML framework at top-level in any generated app/ file
# ---------------------------------------------------------------------------

def test_b06_no_ml_framework_at_top_level(project_dir: Path) -> None:
    """B-06: No torch/sklearn/onnxruntime/numpy/tensorflow at top-level in app/ files."""
    app_dir = project_dir / "app"
    ml_libs = {"torch", "sklearn", "onnxruntime", "numpy", "tensorflow", "ort"}
    violations: list[str] = []

    for py_file in sorted(app_dir.rglob("*.py")):
        try:
            tree = ast.parse(py_file.read_text())
        except SyntaxError:
            continue
        for node in tree.body:  # top-level only
            if isinstance(node, ast.Import):
                for alias in node.names:
                    for lib in ml_libs:
                        if lib in alias.name.split("."):
                            violations.append(
                                f"{py_file.relative_to(project_dir)}:{node.lineno}: import {alias.name}"
                            )
            elif isinstance(node, ast.ImportFrom) and node.module:
                parts = node.module.split(".")
                for lib in ml_libs:
                    if lib in parts:
                        violations.append(
                            f"{py_file.relative_to(project_dir)}:{node.lineno}: "
                            f"from {node.module} import ..."
                        )

    assert not violations, (
        "ML framework found at top-level in the following files:\n"
        + "\n".join(f"  {v}" for v in violations)
    )


