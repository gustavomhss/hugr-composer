# BEHAVIOR-05: app/models/payment.py has correct AST structure
# ---------------------------------------------------------------------------


def test_b05_payment_model_ast_structure(project_dir: Path) -> None:
    """B-05: app/models/payment.py declares ``class Payment`` with the
    required columns at AST level (SQLAlchemy ORM models cannot be
    exec'd standalone due to ``from __future__ import annotations``).
    """
    model_file = project_dir / "app" / "models" / "payment.py"
    assert model_file.exists(), "app/models/payment.py not found"

    content = model_file.read_text()
    tree = ast.parse(content)

    class_names = [node.name for node in ast.walk(tree) if isinstance(node, ast.ClassDef)]
    assert "Payment" in class_names, (
        f"class Payment not found in app/models/payment.py; classes: {class_names}"
    )

    payment_fields: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "Payment":
            for item in node.body:
                if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                    payment_fields.append(item.target.id)

    for required_field in [
        "id",
        "stripe_session_id",
        "amount_cents",
        "currency",
        "status",
        "created_at",
    ]:
        assert required_field in payment_fields, (
            f"Required field '{required_field}' not in Payment model; found: {payment_fields}"
        )


