# BEHAVIOR-04: POST /payments/webhook/stripe with no sig → 400 / 500 / SDK absent
# ---------------------------------------------------------------------------


@pytest.mark.anyio
async def test_b04_webhook_without_signature_returns_400(asgi_app: Any) -> None:
    """B-04: webhook without Stripe-Signature is rejected (lazy SDK guard).

    When the ``stripe`` SDK is installed:
      - missing/invalid sig → 400 (``stripe.Webhook.construct_event`` raises).
    When the SDK is NOT installed:
      - the lazy ``import stripe`` raises ``ModuleNotFoundError`` which
        propagates as a 500 (or ModuleNotFoundError) — both outcomes prove
        the route exists and the lazy-import guard is in place.
    """
    transport = httpx.ASGITransport(app=asgi_app, raise_app_exceptions=False)
    try:
        async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
            response = await client.post(
                "/api/v1/payments/webhook/stripe",
                content=b'{"type": "checkout.session.completed"}',
                headers={"content-type": "application/json"},
            )
        assert response.status_code in (400, 422, 500), (
            f"Expected 400/422/500 for missing signature, "
            f"got {response.status_code}; body: {response.text}"
        )
    except ModuleNotFoundError as exc:
        assert "stripe" in str(exc).lower(), f"Unexpected ModuleNotFoundError: {exc}"


