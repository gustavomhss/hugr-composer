# B-04: ImportProcessor.parse_csv splits header + rows
# ---------------------------------------------------------------------------


def test_b04_import_processor_parse_csv(project_dir: Path) -> None:
    """B-04: ImportProcessor.parse_csv returns row dicts keyed by header columns."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.imports.processor import ImportProcessor  # type: ignore[import-not-found]

        proc = ImportProcessor()
        rows = proc.parse_csv(b"id,name\n1,alice\n2,bob\n")
        assert len(rows) == 2, f"expected 2 rows, got {len(rows)}: {rows}"
        assert rows[0] == {"id": "1", "name": "alice"}, f"row 0 mismatch: {rows[0]}"
        assert rows[1] == {"id": "2", "name": "bob"}, f"row 1 mismatch: {rows[1]}"
    finally:
        sys.path[:] = _orig_path


