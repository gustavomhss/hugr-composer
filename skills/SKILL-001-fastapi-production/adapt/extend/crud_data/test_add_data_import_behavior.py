# B-03: RowValidator surfaces required-field errors per row
# ---------------------------------------------------------------------------


def test_b03_row_validator_required_fields(project_dir: Path) -> None:
    """B-03: RowValidator(required_fields=['name']).validate rejects empty rows."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.imports.validators import RowValidator  # type: ignore[import-not-found]

        v = RowValidator(required_fields=["name"])
        errs = v.validate({"name": ""}, 0)
        assert errs and "name" in errs[0], (
            f"expected required-field error for empty 'name', got {errs}"
        )
        ok = v.validate({"name": "alice"}, 0)
        assert ok == [], f"valid row must produce no errors, got {ok}"
    finally:
        sys.path[:] = _orig_path


