_SQLITE_DB_PY = textwrap.dedent("""\
    \"\"\"Patched db.py — SQLite+aiosqlite, no Docker required.\"\"\"

    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    engine = create_async_engine(
        "sqlite+aiosqlite:///:memory:",
        echo=False,
        future=True,
        connect_args={"check_same_thread": False},
    )


    async def init_db() -> None:
        \"\"\"Run startup checks (connection test).\"\"\"
        async with engine.begin() as conn:
            await conn.execute(text("SELECT 1"))


    __all__ = ["engine", "init_db"]
""")

_PASSTHROUGH_IDEMPOTENCY_MIDDLEWARE_PY = textwrap.dedent("""\
    \"\"\"Patched middleware/idempotency.py — pass-through stub (no Redis).\"\"\"

    from __future__ import annotations

    from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
    from starlette.requests import Request
    from starlette.responses import Response


    class IdempotencyMiddleware(BaseHTTPMiddleware):
        \"\"\"No-op pass-through stub for testing without Redis.\"\"\"

        async def dispatch(
            self,
            request: Request,
            call_next: RequestResponseEndpoint,
        ) -> Response:
            return await call_next(request)
""")


def _patch_project(project_dir: Path) -> None:
    (project_dir / "app" / "core" / "db.py").write_text(_SQLITE_DB_PY)
    idem_mw = project_dir / "app" / "middleware" / "idempotency.py"
    if idem_mw.exists():
        idem_mw.write_text(_PASSTHROUGH_IDEMPOTENCY_MIDDLEWARE_PY)
    # main.py would call init_idempotency_cache(REDIS_URL) at import time and
    # attempt a Redis connection. Strip that single line so the app boots in
    # the absence of a real Redis broker.
    main_py = project_dir / "app" / "main.py"
    src = main_py.read_text()
    patched = re.sub(
        r"init_idempotency_cache\([^)]*\)\n",
        "init_idempotency_cache  # stubbed by behavior test\n",
        src,
    )
    if patched != src:
        main_py.write_text(patched)


def _load_app(project_dir: Path) -> Any:
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        app_module = importlib.import_module("app.main")
    finally:
        sys.path[:] = _orig_path
    return app_module.app


def _setup_project() -> tuple[Path, Any]:
    project_dir = create_fixture_project(name="bulk_behavior")
    result = add_bulk_operations(ToolInput(project_dir=str(project_dir)))
    assert result.status == "success", (
        f"add_bulk_operations failed: {result.error}\nnotes: {result.notes}"
    )
    _patch_project(project_dir)
    asgi_app = _load_app(project_dir)
    return project_dir, asgi_app


