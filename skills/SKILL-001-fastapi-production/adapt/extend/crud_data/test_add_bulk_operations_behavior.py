def test_b05_idempotency_key_isolates_users(project_dir: Path) -> None:
    """B-05 (R5-O2-D9): the same client Idempotency-Key from two different users
    must produce DIFFERENT cache keys (no cross-user replay) while staying stable
    per user (idempotency still works within a user).

    Execs the emitted ``_scoped_idem_key`` in isolation — it is a pure function
    with no app imports — so the property is verified against the real generated
    code, not a re-implementation.
    """
    import ast
    import types

    content = (project_dir / "app" / "api" / "routes" / "item.py").read_text()
    tree = ast.parse(content)
    src = next(
        (
            ast.get_source_segment(content, n)
            for n in ast.walk(tree)
            if isinstance(n, ast.FunctionDef) and n.name == "_scoped_idem_key"
        ),
        None,
    )
    assert src is not None, "_scoped_idem_key not found in emitted routes"
    ns: dict = {}
    exec(src, ns)  # noqa: S102 — pure helper, no imports, generated by our own tool
    scoped = ns["_scoped_idem_key"]

    alice = types.SimpleNamespace(id="11111111-1111-1111-1111-111111111111")
    bob = types.SimpleNamespace(id="22222222-2222-2222-2222-222222222222")
    assert scoped(alice, "ABC") != scoped(bob, "ABC"), (
        "same Idempotency-Key from different users collides → cross-user replay"
    )
    assert scoped(alice, "ABC") == scoped(alice, "ABC"), "key must be stable per user"
    assert "ABC" in scoped(alice, "ABC"), "scoped key must retain the client key"
