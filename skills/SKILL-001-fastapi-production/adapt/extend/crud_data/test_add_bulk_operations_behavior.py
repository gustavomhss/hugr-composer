@pytest.mark.anyio
async def test_b03_idempotency_cache_handles_no_redis(project_dir: Path) -> None:
    """B-03: IdempotencyCache(None).get/set must NOT raise — Redis outage tolerance."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.core.idempotency import IdempotencyCache

        cache = IdempotencyCache(None)
        assert (await cache.get("any-key")) is None, "get must return None when Redis is down"
        # set must complete silently (no exception) — Redis outage must not break flows.
        await cache.set("any-key", {"payload": True})
    finally:
        sys.path[:] = _orig_path


