@pytest.mark.anyio
async def test_b02_bulk_routes_registered(asgi_app: Any) -> None:
    """B-02: /items/bulk endpoints exist (POST + PATCH + DELETE — not 404)."""
    transport = httpx.ASGITransport(app=asgi_app, raise_app_exceptions=False)
    async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
        post_resp = await client.post(
            "/api/v1/items/bulk", json={"items": [], "mode": "all_or_nothing"}
        )
        patch_resp = await client.patch(
            "/api/v1/items/bulk", json={"updates": [], "mode": "all_or_nothing"}
        )
        delete_resp = await client.request(
            "DELETE", "/api/v1/items/bulk", json={"ids": [], "mode": "all_or_nothing"}
        )
    assert post_resp.status_code != 404, (
        f"POST /api/v1/items/bulk not registered: {post_resp.status_code}; body: {post_resp.text}"
    )
    assert patch_resp.status_code != 404, (
        f"PATCH /api/v1/items/bulk not registered: {patch_resp.status_code}; body: {patch_resp.text}"
    )
    assert delete_resp.status_code != 404, (
        f"DELETE /api/v1/items/bulk not registered: {delete_resp.status_code}; body: {delete_resp.text}"
    )


