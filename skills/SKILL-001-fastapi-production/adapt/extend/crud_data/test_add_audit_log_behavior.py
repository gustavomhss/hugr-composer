# ---------------------------------------------------------------------------
# B-03: HMAC key derives from SECRET_KEY (never empty, never hardcoded)
# ---------------------------------------------------------------------------


def test_b03_hmac_key_non_empty_and_derived(project_dir: Path) -> None:
    """B-03: _audit_hmac_secret() returns 32+ bytes derived from SECRET_KEY."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    try:
        from app.audit_log import _audit_hmac_secret

        key = _audit_hmac_secret()
        assert isinstance(key, bytes), "HMAC key must be bytes"
        assert len(key) >= 32, f"HMAC key too short: {len(key)} bytes"
        # SHA-256 derivation from a fixed SECRET_KEY is deterministic.
        assert key == _audit_hmac_secret(), "HMAC key derivation must be deterministic"
    finally:
        sys.path[:] = _orig_path


# ---------------------------------------------------------------------------
# B-04: AUDIT_LOG_HMAC_SECRET env override is honored
# ---------------------------------------------------------------------------


def test_b04_env_override_honored(project_dir: Path) -> None:
    """B-04: AUDIT_LOG_HMAC_SECRET env override replaces the derived key."""
    _orig_path = sys.path.copy()
    sys.path.insert(0, str(project_dir))
    stale = [k for k in sys.modules if k == "app" or k.startswith("app.")]
    for key in stale:
        del sys.modules[key]
    os.environ["AUDIT_LOG_HMAC_SECRET"] = "override-secret-from-env"
    try:
        from app.audit_log import _audit_hmac_secret

        key = _audit_hmac_secret()
        assert key == b"override-secret-from-env", f"env override not honored; got {key!r}"
    finally:
        os.environ.pop("AUDIT_LOG_HMAC_SECRET", None)
        sys.path[:] = _orig_path


# ---------------------------------------------------------------------------
# B-05: main.py wiring is idempotent (rerun adds no second install call)
# ---------------------------------------------------------------------------


def test_b05_main_wiring_idempotent(project_dir: Path) -> None:
    """B-05: install_audit_log(app) appears exactly once in main.py."""
    main_py = (project_dir / "app" / "main.py").read_text()
    assert main_py.count("install_audit_log(app)") == 1, (
        "install_audit_log(app) must appear exactly once after tool runs"
    )
    # Run again — should be a no_op and main.py untouched.
    r2 = add_audit_log(ToolInput(project_dir=str(project_dir)))
    assert r2.status == "no_op"
    main_py_after = (project_dir / "app" / "main.py").read_text()
    assert main_py == main_py_after, "main.py must not change on no_op rerun"
