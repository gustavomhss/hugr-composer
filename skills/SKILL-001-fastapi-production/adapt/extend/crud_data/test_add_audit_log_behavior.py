"""BEHAVIOR TEST — TOOL-005 add_audit_log.

Proves that the code generated by ``add_audit_log`` works at **runtime**:
boots a real ASGI app and verifies the tamper-evident audit log is wired,
the /audit-logs router is registered, and the HMAC key is non-empty.

Patches applied (so tests run without Docker):
- ``app/core/db.py``               → SQLite + aiosqlite (no Postgres)
- ``app/middleware/idempotency.py`` → pass-through stub (no Redis)
- ``REDIS_URL`` env var             → removed

Run::

    PYTHONPATH=. .venv/bin/pytest adapt/extend/crud_data/test_add_audit_log_behavior.py -v
"""

