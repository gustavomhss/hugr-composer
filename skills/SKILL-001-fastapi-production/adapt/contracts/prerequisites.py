def ensure_prerequisites(
    project_dir: str | Path,
    *prereqs: Prereq,
    auto_scaffold: bool = False,
) -> tuple[list[str], list[str]]:
    """Check prerequisites and optionally auto-scaffold missing ones.

    Convenience wrapper that combines ``check_prerequisites`` +
    ``scaffold_prerequisites``. When ``auto_scaffold=True``, missing
    prerequisites are created automatically before returning.

    Args:
        project_dir: Root of the FastAPI project.
        *prereqs: Prerequisites to check (and optionally scaffold).
        auto_scaffold: When ``True``, create missing prerequisites instead
            of returning errors. Only scaffoldable prereqs are created;
            non-scaffoldable ones (like AUTH_DEPS) still return errors.

    Returns:
        Tuple of ``(errors, scaffolded_files)``.

        * ``errors``: remaining prerequisite errors AFTER scaffolding
          (empty if everything was resolved).
        * ``scaffolded_files``: paths created during auto-scaffolding
          (empty if ``auto_scaffold=False`` or nothing was missing).
    """
    errors = check_prerequisites(project_dir, *prereqs)
    if not errors or not auto_scaffold:
        return errors, []

    # Scaffold what we can, then re-check for anything that couldn't
    # be auto-created (e.g., AUTH_DEPS requires full auth stack)
    scaffolded = scaffold_prerequisites(project_dir, *prereqs)
    remaining = check_prerequisites(project_dir, *prereqs)
    return remaining, scaffolded


def scaffold_prerequisites(
    project_dir: str | Path,
    *prereqs: Prereq,
) -> list[str]:
    """Auto-create missing prerequisites with minimal, functional content.

    Only creates files that are actually missing — existing files are
    NEVER overwritten. This makes adapt tools work on ANY FastAPI project,
    not just ones generated by the skill.

    Args:
        project_dir: Root of the FastAPI project.
        *prereqs: Prerequisites to scaffold if missing.

    Returns:
        List of ABSOLUTE paths to ``.py`` files that were created. Empty
        if everything already existed. Non-Python artefacts (``.gitkeep``,
        ``requirements.txt``, alembic versions directory) are scaffolded
        on disk but NOT included in the return list, because downstream
        tools iterate the list and call ``ast.parse(p.read_text())`` on
        every entry, which crashes on non-Python content.
    """
    created: list[str] = []
    root = Path(project_dir).resolve()

    def _record(path: Path) -> None:
        """Append *path* to ``created`` only when it is a real ``.py`` file.

        Non-Python scaffold artefacts (requirements.txt, .gitkeep, etc.)
        are excluded so downstream ``_validate_py`` loops in adapt tools
        don't choke on them.
        """
        if path.suffix == ".py" and path.is_file():
            created.append(str(path))

    # Collect the set of paths that have explicit scaffold content so the
    # parent-package __init__.py creation below doesn't pre-empt them with
    # a generic placeholder (e.g. MODELS_INIT targets app/models/__init__.py).
    explicit_targets: set[str] = set()
    for prereq in prereqs:
        if prereq in _SCAFFOLDS:
            explicit_targets.add(_SCAFFOLDS[prereq][0])

    # Ensure the app/ package exists
    app_init = root / "app" / "__init__.py"
    if not app_init.exists() and "app/__init__.py" not in explicit_targets:
        app_init.parent.mkdir(parents=True, exist_ok=True)
        app_init.write_text('"""Application package."""\n')
        _record(app_init)

    for prereq in prereqs:
        if prereq not in _SCAFFOLDS:
            continue

        rel_path, content = _SCAFFOLDS[prereq]
        target = root / rel_path

        if prereq == Prereq.ALEMBIC_VERSIONS:
            versions_dir = root / "alembic" / "versions"
            if not versions_dir.is_dir():
                versions_dir.mkdir(parents=True, exist_ok=True)
                (versions_dir / ".gitkeep").write_text("")
                # Directory created, but NOT appended to ``created``: the
                # list is consumed by downstream tools that iterate it and
                # call ``ast.parse(p.read_text())``. A directory path or a
                # non-Python placeholder file would crash that loop. The
                # scaffolded directory is represented implicitly by the
                # absence of the crash, not by a list entry.
            continue

        if target.exists():
            continue

        target.parent.mkdir(parents=True, exist_ok=True)
        # Ensure parent package __init__.py exists
        for parent in target.relative_to(root).parents:
            if parent == Path("."):
                continue
            parent_init = root / parent / "__init__.py"
            if not parent_init.exists() and (root / parent).is_dir():
                # Don't create a generic placeholder if this path has an
                # explicit scaffold (will be written by a later iteration).
                parent_rel = str(parent / "__init__.py")
                if parent_rel in explicit_targets:
                    continue
                parent_init.write_text(f'"""{parent.name} package."""\n')
                _record(parent_init)

        target.write_text(content)
        _record(target)

    return created
