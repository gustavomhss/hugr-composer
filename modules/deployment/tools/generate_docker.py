def generate_dockerfile(
    project_name: str,
    python_version: str = "3.12",
    port: int = 8000,
    workers: int = 4,
    *,
    use_gunicorn: bool = False,
    requirements_file: str = "requirements.txt",
    app_module: str = "main:app",
    graceful_shutdown_timeout: int = 30,
) -> str:
    """
    Generate a production-grade multi-stage Dockerfile for a FastAPI application.

    The generated Dockerfile follows SOTA practices:
      - Multi-stage build: builder stage installs dependencies with pip,
        runtime stage copies only installed packages (no compilers/headers).
      - Layer cache: ``COPY requirements.txt`` before ``COPY .`` ensures
        pip install is cached when only source code changes.
      - Non-root: dedicated ``app`` user (UID 10001) with no login shell.
      - No pip cache: ``--no-cache-dir`` saves 100-200MB in the builder layer.
      - HEALTHCHECK: built-in Docker health check against /healthz.
      - Graceful shutdown: ``--timeout-graceful-shutdown`` for Uvicorn.

    Args:
        project_name: Used in labels and comments.
        python_version: Python version for base image (default: "3.12").
        port: Port the application listens on (default: 8000).
        workers: Number of Uvicorn/Gunicorn workers (default: 4).
            In Kubernetes, use 1 (K8s manages replicas via HPA).
        use_gunicorn: Use Gunicorn with Uvicorn workers. Only for non-K8s
            deployments (single VM/container). Default: False.
        requirements_file: Path to requirements file (default: "requirements.txt").
        app_module: ASGI app module path (default: "main:app").
        graceful_shutdown_timeout: Seconds to wait for in-flight requests
            after SIGTERM (default: 30).

    Returns:
        String containing the complete Dockerfile content.

    Example::

        dockerfile = generate_dockerfile("billing-api", python_version="3.12")
        Path("Dockerfile").write_text(dockerfile)

        # For Kubernetes (1 worker per pod, HPA scales pods):
        dockerfile = generate_dockerfile("billing-api", workers=1)

        # For single VM with Gunicorn:
        dockerfile = generate_dockerfile("billing-api", use_gunicorn=True, workers=4)
    """
    # Build the CMD based on whether we use Gunicorn or Uvicorn directly
    if use_gunicorn:
        cmd_line = (
            f'CMD ["gunicorn", "{app_module}", '
            f'"--bind", "0.0.0.0:{port}", '
            f'"--workers", "{workers}", '
            f'"--worker-class", "uvicorn.workers.UvicornWorker", '
            f'"--timeout", "120", '
            f'"--graceful-timeout", "{graceful_shutdown_timeout}", '
            f'"--access-logfile", "-"]'
        )
        extra_requirements = "\n# Gunicorn for multi-worker process management\nRUN pip install --no-cache-dir gunicorn"
    else:
        cmd_line = (
            f'CMD ["uvicorn", "{app_module}", '
            f'"--host", "0.0.0.0", '
            f'"--port", "{port}", '
            f'"--workers", "{workers}", '
            f'"--timeout-graceful-shutdown", "{graceful_shutdown_timeout}"]'
        )
        extra_requirements = ""

    return textwrap.dedent(f"""\
        # =============================================================================
        # {project_name} — Production Dockerfile
        # Generated by SKILL-001 Deployment Module
        # =============================================================================
        #
        # Build:  docker build -t {project_name}:latest .
        # Run:    docker run -p {port}:{port} --env-file .env {project_name}:latest
        # Scan:   trivy image {project_name}:latest --severity CRITICAL,HIGH
        #
        # Image size: ~150-200MB (vs ~1.1GB for single-stage python:3.12)
        # Security:   Non-root (UID 10001), no pip cache, no compilers in runtime
        # =============================================================================

        # ---------------------------------------------------------------------------
        # Stage 1: Builder — install Python dependencies with build tools
        # ---------------------------------------------------------------------------
        FROM python:{python_version}-slim AS builder

        WORKDIR /build

        # Copy ONLY requirements first — layer cache survives source code changes.
        # When requirements.txt hasn't changed, Docker reuses the cached pip install
        # layer, saving 30-120 seconds per build.
        COPY {requirements_file} .
        RUN pip install --no-cache-dir --prefix=/install -r {requirements_file}{extra_requirements}

        # ---------------------------------------------------------------------------
        # Stage 2: Runtime — minimal image with only what the app needs
        # ---------------------------------------------------------------------------
        FROM python:{python_version}-slim

        LABEL maintainer="{project_name}-team"
        LABEL org.opencontainers.image.source="https://github.com/org/{project_name}"
        LABEL org.opencontainers.image.description="{project_name} FastAPI service"

        # Create non-root user BEFORE copying files.
        # UID 10001 avoids conflicts with system users (0-999) and common UIDs (1000).
        # /sbin/nologin prevents interactive login if container is compromised.
        RUN groupadd -r app && useradd -r -g app -d /app -s /sbin/nologin -u 10001 app

        WORKDIR /app

        # Copy installed packages from builder stage (no compilers, headers, or cache)
        COPY --from=builder /install /usr/local

        # Copy application source code LAST (changes most frequently → cache-friendly)
        COPY . .

        # Fix ownership and switch to non-root user
        RUN chown -R app:app /app
        USER app

        EXPOSE {port}

        # Built-in health check for Docker (also used by docker-compose, ECS, etc.)
        # Kubernetes uses its own probes (livenessProbe, readinessProbe) instead.
        HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\
            CMD ["python", "-c", "import httpx; httpx.get('http://localhost:{port}/healthz').raise_for_status()"]

        {cmd_line}
    """)


