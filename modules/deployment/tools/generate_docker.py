"""
SKILL-001 Deployment Tool: Generate a production-grade Dockerfile.

Creates a SOTA multi-stage Dockerfile for FastAPI/Python applications with:
  - Two-stage build (builder + runtime) for minimal image size (~150MB)
  - Non-root user (UID 10001) with read-only root filesystem support
  - Layer cache optimization (requirements copied before source)
  - No pip cache (--no-cache-dir) in builder
  - Built-in HEALTHCHECK using the /healthz endpoint
  - Configurable Python version, port, and worker count
  - Security: no secrets in build args, drop all capabilities hint
  - .dockerignore generation to prevent context bloat
"""

