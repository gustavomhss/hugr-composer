def analyze_dockerfile(dockerfile_content: str) -> list[Finding]:
    """
    Analyze an existing Dockerfile for production anti-patterns.

    Checks for 8 common issues: running as root, missing HEALTHCHECK,
    single-stage build, pip cache left in image, secrets in build args,
    unpinned base image, missing .dockerignore patterns, and COPY . before
    requirements.

    Args:
        dockerfile_content: The raw content of a Dockerfile to analyze.

    Returns:
        List of Finding objects for detected anti-patterns, sorted by severity.

    Example::

        content = Path("Dockerfile").read_text()
        findings = analyze_dockerfile(content)
        for f in findings:
            print(f"[{f.severity.value}] {f.rule_id}: {f.title}")
    """
    findings: list[Finding] = []
    lines = dockerfile_content.splitlines()
    lower_content = dockerfile_content.lower()

    # DOCKER-01: Running as root (no USER directive)
    has_user = any(
        line.strip().upper().startswith("USER ")
        for line in lines
        if not line.strip().startswith("#")
    )
    if not has_user:
        findings.append(Finding(
            rule_id="DOCKER-01",
            severity=Severity.HIGH,
            title="Container runs as root",
            description=(
                "No USER directive found. Container processes run as root (UID 0), "
                "which gives an attacker full system access if the app is compromised. "
                "Many K8s clusters enforce non-root via PodSecurityPolicy/Standards."
            ),
            fix_suggestion=(
                "Add a non-root user: "
                "RUN groupadd -r app && useradd -r -g app -u 10001 app; "
                "then USER app before CMD."
            ),
        ))

    # DOCKER-02: No HEALTHCHECK
    has_healthcheck = "HEALTHCHECK" in dockerfile_content
    if not has_healthcheck:
        findings.append(Finding(
            rule_id="DOCKER-02",
            severity=Severity.MEDIUM,
            title="No HEALTHCHECK instruction",
            description=(
                "Docker cannot determine if the app inside the container is healthy. "
                "docker-compose and ECS rely on HEALTHCHECK for restart decisions."
            ),
            fix_suggestion=(
                'HEALTHCHECK --interval=30s --timeout=5s --retries=3 '
                'CMD ["python", "-c", "import httpx; '
                "httpx.get('http://localhost:8000/healthz').raise_for_status()\"]"
            ),
        ))

    # DOCKER-03: Single-stage build (no AS keyword)
    from_count = sum(
        1 for line in lines
        if line.strip().upper().startswith("FROM ")
        and not line.strip().startswith("#")
    )
    has_multistage = from_count >= 2
    if not has_multistage:
        findings.append(Finding(
            rule_id="DOCKER-03",
            severity=Severity.MEDIUM,
            title="Single-stage build detected",
            description=(
                "Only one FROM stage found. Build tools (gcc, pip cache, headers) "
                "remain in the final image, increasing size by 500MB+ and attack surface."
            ),
            fix_suggestion=(
                "Use multi-stage: FROM python:3.12-slim AS builder for deps, "
                "then FROM python:3.12-slim for runtime with COPY --from=builder."
            ),
        ))

    # DOCKER-04: pip cache not disabled
    has_pip_install = "pip install" in lower_content
    has_no_cache = "--no-cache-dir" in lower_content
    if has_pip_install and not has_no_cache:
        findings.append(Finding(
            rule_id="DOCKER-04",
            severity=Severity.LOW,
            title="pip cache not disabled",
            description=(
                "pip install without --no-cache-dir leaves 100-200MB of cached "
                "wheels in the image. These are never reused in a container."
            ),
            fix_suggestion="Add --no-cache-dir to all pip install commands.",
        ))

    # DOCKER-05: Secrets in build args
    import re
    secret_args = re.findall(
        r"ARG\s+(\w*(?:SECRET|PASSWORD|KEY|TOKEN)\w*)",
        dockerfile_content,
        re.IGNORECASE,
    )
    if secret_args:
        findings.append(Finding(
            rule_id="DOCKER-05",
            severity=Severity.CRITICAL,
            title=f"Potential secrets in ARG: {', '.join(secret_args)}",
            description=(
                "ARG values are baked into image layer history and visible via "
                "'docker history'. Anyone with image access can extract them."
            ),
            fix_suggestion=(
                "Use --mount=type=secret for build-time secrets, or pass "
                "secrets at runtime via environment variables / K8s Secrets."
            ),
        ))

    # DOCKER-06: Unpinned base image (no version tag or digest)
    for line in lines:
        stripped = line.strip()
        if stripped.upper().startswith("FROM ") and not stripped.startswith("#"):
            image_ref = stripped.split()[1] if len(stripped.split()) > 1 else ""
            if image_ref and ":" not in image_ref and "@" not in image_ref:
                findings.append(Finding(
                    rule_id="DOCKER-06",
                    severity=Severity.HIGH,
                    title=f"Unpinned base image: {image_ref}",
                    description=(
                        f"Base image '{image_ref}' has no version tag or digest. "
                        "A compromised or updated upstream image silently changes "
                        "your build, potentially introducing vulnerabilities."
                    ),
                    fix_suggestion=(
                        "Pin with version tag (python:3.12-slim) or SHA256 digest "
                        "(python:3.12-slim@sha256:abc...) for immutable builds."
                    ),
                ))
            break  # Only check first FROM

    # DOCKER-07: COPY . before requirements (cache-busting)
    copy_dot_line: int | None = None
    copy_req_line: int | None = None
    for i, line in enumerate(lines, 1):
        stripped = line.strip()
        if stripped.startswith("COPY . ") or stripped == "COPY . .":
            if copy_dot_line is None:
                copy_dot_line = i
        if "requirements" in stripped.lower() and stripped.startswith("COPY"):
            if copy_req_line is None:
                copy_req_line = i

    if (
        copy_dot_line is not None
        and copy_req_line is not None
        and copy_dot_line < copy_req_line
    ):
        findings.append(Finding(
            rule_id="DOCKER-07",
            severity=Severity.MEDIUM,
            title="COPY . before COPY requirements (breaks layer cache)",
            description=(
                f"COPY . at line {copy_dot_line} comes before COPY requirements "
                f"at line {copy_req_line}. Every source code change invalidates "
                "the pip install layer, causing full reinstalls on every build."
            ),
            line_number=copy_dot_line,
            fix_suggestion=(
                "Move COPY requirements.txt . and RUN pip install BEFORE COPY . ."
            ),
        ))

    # Sort by severity
    severity_order = {
        Severity.CRITICAL: 0,
        Severity.HIGH: 1,
        Severity.MEDIUM: 2,
        Severity.LOW: 3,
    }
    findings.sort(key=lambda f: severity_order.get(f.severity, 99))

    return findings
