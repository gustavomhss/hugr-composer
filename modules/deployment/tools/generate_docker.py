def generate_dockerignore(project_name: str | None = None) -> str:
    """
    Generate a .dockerignore file to minimize Docker build context.

    Excludes version control, virtual environments, caches, IDE files,
    documentation, and test artifacts. This can reduce build context
    from 500MB+ to under 10MB, dramatically speeding up builds.

    Args:
        project_name: Optional project name for comments.

    Returns:
        String containing the .dockerignore content.

    Example::

        dockerignore = generate_dockerignore("billing-api")
        Path(".dockerignore").write_text(dockerignore)
    """
    header = f"# {project_name} — Docker build context exclusions\n" if project_name else ""

    return textwrap.dedent(f"""\
        {header}# Version control
        .git
        .gitignore

        # Python
        __pycache__
        *.pyc
        *.pyo
        *.egg-info
        dist
        build
        .eggs

        # Virtual environments
        .venv
        venv
        env

        # IDE
        .vscode
        .idea
        *.swp
        *.swo

        # Testing & CI
        .pytest_cache
        .mypy_cache
        .ruff_cache
        .coverage
        htmlcov
        .tox

        # Documentation
        docs
        *.md
        LICENSE

        # Docker (prevent recursive context)
        Dockerfile
        docker-compose*.yml
        .dockerignore

        # Environment files (NEVER include secrets in image)
        .env
        .env.*

        # OS files
        .DS_Store
        Thumbs.db

        # Kubernetes manifests (not needed in container)
        k8s/
        *.yaml
        !requirements*.yaml
    """)


