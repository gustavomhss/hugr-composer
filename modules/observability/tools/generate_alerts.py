def generate_alerting_rules(
    service_name: str,
    slo_availability: float = 0.999,
    slo_latency_p99_ms: int = 500,
    output_dir: str | None = None,
) -> dict[str, str]:
    """
    Generate Prometheus alerting rules and a Grafana dashboard for an API service.

    Creates two files:
    1. ``prometheus_rules.yaml`` — Recording rules for error ratios, burn rates,
       and latency percentiles, plus multi-window multi-burn-rate alert rules
       following the Google SRE Workbook pattern (Chapter 5).
    2. ``grafana_dashboard.json`` — Importable Grafana dashboard with the Four
       Golden Signals (Latency, Traffic, Errors, Saturation) plus SLO error
       budget panels.

    Alert severity mapping:
        - **critical** (page): Fast burn (14.4x), error budget < 10%
        - **warning** (page): Medium burn (6x), p99 latency exceeded
        - **info** (ticket): Slow burn (1x), budget consumption on track to fail

    Args:
        service_name: Service name used in metric labels and alert names.
            Must match the ``service`` label on your Prometheus metrics.
        slo_availability: Availability SLO as a fraction (default 0.999 = 99.9%).
            Error budget = 1 - slo_availability.
        slo_latency_p99_ms: Maximum acceptable p99 latency in milliseconds
            (default 500ms).
        output_dir: Directory to write files. If None, returns content without
            writing to disk.

    Returns:
        Dict mapping filename to file content:
        ``{"prometheus_rules.yaml": "...", "grafana_dashboard.json": "..."}``

    Example::

        files = generate_alerting_rules(
            service_name="order-api",
            slo_availability=0.999,
            slo_latency_p99_ms=500,
            output_dir="/tmp/monitoring",
        )
        print(files.keys())
        # dict_keys(['prometheus_rules.yaml', 'grafana_dashboard.json'])
    """
    if not 0 < slo_availability < 1:
        raise ValueError(
            f"slo_availability must be between 0 and 1 (exclusive), "
            f"got {slo_availability}"
        )

    if slo_latency_p99_ms <= 0:
        raise ValueError(
            f"slo_latency_p99_ms must be positive, got {slo_latency_p99_ms}"
        )

    # Generate content
    prometheus_yaml = _generate_prometheus_rules(
        service_name, slo_availability, slo_latency_p99_ms,
    )

    grafana_model = _generate_grafana_dashboard(
        service_name, slo_availability, slo_latency_p99_ms,
    )
    grafana_json = json.dumps(grafana_model, indent=2, ensure_ascii=False)

    result = {
        "prometheus_rules.yaml": prometheus_yaml,
        "grafana_dashboard.json": grafana_json,
    }

    # Write to disk if output_dir is specified
    if output_dir is not None:
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)

        for filename, content in result.items():
            filepath = out_path / filename
            filepath.write_text(content, encoding="utf-8")

    return result
