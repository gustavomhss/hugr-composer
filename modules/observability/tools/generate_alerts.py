def _generate_prometheus_rules(
    service_name: str,
    slo_availability: float,
    slo_latency_p99_ms: int,
) -> str:
    """Generate Prometheus recording rules and multi-burn-rate alert rules.

    Follows the Google SRE Workbook multi-window multi-burn-rate pattern:
    - Fast burn (14.4x): pages immediately — 2% budget consumed in 1 hour
    - Medium burn (6x): pages — 5% budget consumed in 6 hours
    - Slow burn (1x): creates ticket — on track to exhaust budget
    """
    error_budget = round(1.0 - slo_availability, 6)
    latency_threshold_s = slo_latency_p99_ms / 1000.0

    # Calculate burn rates from the Google SRE Workbook table:
    # burn_rate = (1 / (1 - slo)) * (budget_consumed / hours * (window_hours / 720))
    # Simplified: for 30-day window, burn_rate_14.4 exhausts budget in ~50h
    fast_burn = 14.4
    medium_burn = 6.0
    slow_burn = 1.0

    return textwrap.dedent(f"""\
        # =======================================================================
        # Prometheus Alerting Rules — {service_name}
        # =======================================================================
        #
        # Generated by SKILL-001 Observability Module.
        #
        # SLO targets:
        #   Availability: {slo_availability * 100:.1f}% (error budget: {error_budget})
        #   Latency p99:  {slo_latency_p99_ms}ms
        #
        # Alert strategy: Multi-window multi-burn-rate (Google SRE Workbook Ch.5)
        #   Fast burn (14.4x):  PAGE  — exhausts 30-day budget in ~50 hours
        #   Medium burn (6x):   PAGE  — exhausts 30-day budget in ~5 days
        #   Slow burn (1x):     TICKET — on track to exhaust budget at window end
        #
        # Short windows prevent stale alerts from resolved incidents.
        # Rule of thumb: short_window = long_window / 12
        #
        # Installation:
        #   Copy to /etc/prometheus/rules/ and reload Prometheus:
        #   curl -X POST http://localhost:9090/-/reload
        #
        # =======================================================================

        groups:
          # -------------------------------------------------------------------
          # Recording rules: pre-compute error ratios and latency over windows
          # -------------------------------------------------------------------
          - name: {service_name}_slo_recording
            interval: 30s
            rules:
              # Error ratio: fraction of 5xx responses over each window
              - record: {service_name}:error_ratio:5m
                expr: |
                  sum(rate(http_requests_total{{service="{service_name}", status=~"5.."}}[5m]))
                  / sum(rate(http_requests_total{{service="{service_name}"}}[5m]))

              - record: {service_name}:error_ratio:30m
                expr: |
                  sum(rate(http_requests_total{{service="{service_name}", status=~"5.."}}[30m]))
                  / sum(rate(http_requests_total{{service="{service_name}"}}[30m]))

              - record: {service_name}:error_ratio:1h
                expr: |
                  sum(rate(http_requests_total{{service="{service_name}", status=~"5.."}}[1h]))
                  / sum(rate(http_requests_total{{service="{service_name}"}}[1h]))

              - record: {service_name}:error_ratio:6h
                expr: |
                  sum(rate(http_requests_total{{service="{service_name}", status=~"5.."}}[6h]))
                  / sum(rate(http_requests_total{{service="{service_name}"}}[6h]))

              # Burn rate: error_ratio / error_budget
              # burn_rate = 1.0 means budget consumed exactly at window end
              # burn_rate > 1.0 means budget will be exhausted early
              - record: {service_name}:burn_rate:1h
                expr: |
                  {service_name}:error_ratio:1h / {error_budget}

              - record: {service_name}:burn_rate:6h
                expr: |
                  {service_name}:error_ratio:6h / {error_budget}

              # Latency p99 over 5-minute window
              - record: {service_name}:latency_p99:5m
                expr: |
                  histogram_quantile(0.99,
                    sum(rate(http_request_duration_seconds_bucket{{service="{service_name}"}}[5m])) by (le)
                  )

              # Request rate (for traffic panel)
              - record: {service_name}:request_rate:5m
                expr: |
                  sum(rate(http_requests_total{{service="{service_name}"}}[5m]))

              # Error budget remaining (fraction of budget not yet consumed)
              - record: {service_name}:error_budget_remaining:30d
                expr: |
                  1 - (
                    sum(increase(http_requests_total{{service="{service_name}", status=~"5.."}}[30d]))
                    / sum(increase(http_requests_total{{service="{service_name}"}}[30d]))
                  ) / {error_budget}

          # -------------------------------------------------------------------
          # Alert rules: multi-window multi-burn-rate
          # -------------------------------------------------------------------
          - name: {service_name}_slo_alerts
            rules:
              # ---------------------------------------------------------------
              # FAST BURN — PAGE (critical)
              # 14.4x burn rate = exhausts 30-day budget in ~50 hours
              # Long window: 1h, Short window: 5m (1h / 12)
              # ---------------------------------------------------------------
              - alert: {service_name}_SLO_FastBurn
                expr: |
                  {service_name}:error_ratio:1h / {error_budget} > {fast_burn}
                  and
                  {service_name}:error_ratio:5m / {error_budget} > {fast_burn}
                for: 2m
                labels:
                  service: {service_name}
                  severity: critical
                  slo: availability
                  alert_type: page
                annotations:
                  summary: "CRITICAL: {{{{ $labels.service }}}} burning error budget at {fast_burn}x rate"
                  description: |
                    Error burn rate is {fast_burn}x the budget.
                    At this rate, the 30-day error budget will be exhausted in ~50 hours.
                    Current 1h error ratio: {{{{ $value | humanizePercentage }}}}
                    Error budget: {error_budget} ({slo_availability * 100:.1f}% SLO)
                  runbook: "https://wiki.example.com/runbooks/{service_name}/slo-fast-burn"

              # ---------------------------------------------------------------
              # MEDIUM BURN — PAGE (warning)
              # 6x burn rate = exhausts 30-day budget in ~5 days
              # Long window: 6h, Short window: 30m (6h / 12)
              # ---------------------------------------------------------------
              - alert: {service_name}_SLO_MediumBurn
                expr: |
                  {service_name}:error_ratio:6h / {error_budget} > {medium_burn}
                  and
                  {service_name}:error_ratio:30m / {error_budget} > {medium_burn}
                for: 5m
                labels:
                  service: {service_name}
                  severity: warning
                  slo: availability
                  alert_type: page
                annotations:
                  summary: "WARNING: {{{{ $labels.service }}}} elevated error burn rate ({medium_burn}x)"
                  description: |
                    Error burn rate is {medium_burn}x the budget over 6 hours.
                    At this rate, the 30-day error budget will be exhausted in ~5 days.
                    Current 6h error ratio: {{{{ $value | humanizePercentage }}}}
                  runbook: "https://wiki.example.com/runbooks/{service_name}/slo-medium-burn"

              # ---------------------------------------------------------------
              # SLOW BURN — TICKET (info)
              # 1x burn rate = on track to exhaust budget at window end
              # Long window: 6h, Short window: 1h
              # ---------------------------------------------------------------
              - alert: {service_name}_SLO_SlowBurn
                expr: |
                  {service_name}:error_ratio:6h / {error_budget} > {slow_burn}
                  and
                  {service_name}:error_ratio:1h / {error_budget} > {slow_burn}
                for: 30m
                labels:
                  service: {service_name}
                  severity: info
                  slo: availability
                  alert_type: ticket
                annotations:
                  summary: "INFO: {{{{ $labels.service }}}} error rate above SLO budget"
                  description: |
                    Sustained error rate above SLO budget.
                    If this continues, the 30-day error budget will be exhausted.
                    Current 6h error ratio: {{{{ $value | humanizePercentage }}}}
                  runbook: "https://wiki.example.com/runbooks/{service_name}/slo-slow-burn"

              # ---------------------------------------------------------------
              # LATENCY SLO — TICKET
              # p99 latency exceeds target for sustained period
              # ---------------------------------------------------------------
              - alert: {service_name}_SLO_LatencyHigh
                expr: |
                  {service_name}:latency_p99:5m > {latency_threshold_s}
                for: 10m
                labels:
                  service: {service_name}
                  severity: warning
                  slo: latency
                  alert_type: ticket
                annotations:
                  summary: "WARNING: {{{{ $labels.service }}}} p99 latency exceeds {slo_latency_p99_ms}ms"
                  description: |
                    The 99th percentile request latency has exceeded {slo_latency_p99_ms}ms
                    for more than 10 minutes.
                    Current p99: {{{{ $value | humanizeDuration }}}}
                  runbook: "https://wiki.example.com/runbooks/{service_name}/latency-high"

              # ---------------------------------------------------------------
              # ERROR BUDGET EXHAUSTED — PAGE
              # Less than 10% of error budget remaining
              # ---------------------------------------------------------------
              - alert: {service_name}_ErrorBudgetLow
                expr: |
                  {service_name}:error_budget_remaining:30d < 0.1
                for: 5m
                labels:
                  service: {service_name}
                  severity: critical
                  slo: availability
                  alert_type: page
                annotations:
                  summary: "CRITICAL: {{{{ $labels.service }}}} error budget nearly exhausted"
                  description: |
                    Less than 10% of the 30-day error budget remains.
                    Remaining budget: {{{{ $value | humanizePercentage }}}}
                    Stop feature work and focus on reliability.
                  runbook: "https://wiki.example.com/runbooks/{service_name}/error-budget-exhausted"
    """)


